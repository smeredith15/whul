def _fixture_cell(fixture: dict | None) -> str:
    """What this asset plays next, small, between its name and its score.

    Two shapes. A fixture is a date and an opponent; a tour event is a date and
    a name, because a golfer and a driver turn up to a field rather than to
    somebody. The second is why the cell does not simply always say "vs".

    Empty where nothing is known, and empty deliberately: a league between
    seasons has nothing to play next, and filling that with a guess would make
    the column untrustworthy for the leagues where it is right.
    """
    if not fixture:
        return "<td class='fixture'></td>"
    try:
        when = date.fromisoformat(str(fixture["date"]))
        day = f"{when:%b} {when.day}"
    except (TypeError, ValueError):
        day = str(fixture.get("date", ""))
    against = str(fixture.get("opponent", ""))
    competition = str(fixture.get("competition", ""))
    if not against and competition:
        # A tour event: a field rather than an opponent. "vs" would be a
        # sentence about nobody, so the event's own name takes the slot the
        # opponent has everywhere else.
        full = f"{day} \u00b7 {competition}"
        return (
            f"<td class='fixture event' title=\"{escape(full)}\">"
            f"<span class='when'>{escape(day)}</span>"
            f"<span class='against'>{escape(competition)}</span></td>"
        )
    versus = "vs" if fixture.get("home") else "at"
    badge = str(fixture.get("badge", ""))
    full = f"{day} {versus} {against}" + (f" ({competition})" if badge else "")
    # The opponent is its own element so a narrow screen can break the line
    # there rather than truncating -- a fixture cut to "Sep 20 vs New Or..."
    # has lost the only part anybody reads it for.
    mark = (f"<span class='comp' title=\"{escape(str(fixture.get('competition','')))}\">"
            f"{escape(badge)}</span>") if badge else ""
    return (
        f"<td class='fixture' title=\"{escape(full)}\">"
        f"<span class='when'>{escape(day)}</span>"
        f"<span class='against'><span class='versus'>{escape(versus)}</span> "
        f"{escape(against)}</span>{mark}</td>"
    )


def _write_team(out, manager, managers, bars, store, season, latest, stamp,
                simulated, profiles) -> None:
    """One manager's roster: every slot, with the normalized score it is worth.

    The raw score and the stat lines behind it live in the profile window
    rather than in the table -- there are sixty slots, and a column of raw
    numbers on a scale that differs per league compares nothing to anything.
    """
    mine = bars[bars["manager_id"] == manager] if not bars.empty else bars
    raw = store.query(
        "SELECT asset_id, league_points, scaled_score FROM daily_scores "
        "WHERE season = ? AND as_of = ?",
        (season, str(latest)),
    ).set_index("asset_id")
    upcoming = fixtures.by_asset(store, season, latest)

    sections = []
    total = 0.0
    empty_slots = 0
    for asset_type in ("Player", "Team"):
        rows = []
        block = mine[mine["asset_type"] == asset_type] if not mine.empty else mine
        if block.empty:
            continue
        for category in sorted(block["category"].unique()):
            for row in block[block["category"] == category].sort_values(
                "score", ascending=False
            ).itertuples():
                asset = str(row.asset_id or "")
                # An undrafted slot is shown, not skipped. It is a slot the
                # manager still has to fill, and hiding it would make a roster
                # with a hole look complete.
                if not asset:
                    empty_slots += 1
                    rows.append(
                        f"<tr class='empty'>"
                        f"<td class='slotname'>{escape(category)}</td>"
                        f"<td class='undrafted'>Undrafted</td>"
                        f"<td class='fixture'></td>"
                        f"<td class='num'>—</td></tr>"
                    )
                    continue
                profile = profiles.get(asset)
                name = profile["name"] if profile else asset
                scaled = float(raw.loc[asset, "scaled_score"]) if asset in raw.index else 0.0
                counts = bool(row.counts)
                total += float(row.score) if counts else 0.0
                # A benched slot's score is struck through rather than hidden:
                # it is what the slot would be worth, and seeing it is how a
                # manager knows how close the bench is to the cut.
                value = (
                    f"{scaled:,.1f}" if counts
                    else f'<span class="struck">{scaled:,.1f}</span>'
                )
                rows.append(
                    f"<tr class='{'' if counts else 'bench'}'>"
                    f"<td class='slotname'>{escape(category)}</td>"
                    f"<td>{_asset_button(asset, name, counts, depth=1, profile=profile)}</td>"
                    f"{_fixture_cell(upcoming.get(asset))}"
                    f"<td class='num'>{value}</td></tr>"
                )
        sections.append(
            f"<div class='card'><h2>{asset_type}s</h2>"
            f"<p class='sub'>Normalized score, where 100 is the 99th percentile of a "
            f"draftable pool. Benched slots are struck through. Click a name for the "
            f"raw stats behind the score.</p>"
            "<table><thead><tr><th>Category</th><th>Asset</th>"
            "<th class='fixture'>Next</th>"
            "<th class='num'>Normalized</th></tr></thead>"
            f"<tbody>{''.join(rows)}</tbody></table></div>"
        )

    slot = theme.series_index(managers, manager) + 1

    # The count of unfilled slots used to be a tile of its own. It is one
    # number that changes a handful of times a season, and it sat beside two
    # others in the space where the interesting question is which parts of the
    # roster are carrying the total. The count keeps its place in the sentence
    # under the ring, where it is still read and no longer costs a third of the
    # header.
    mix = _counting_mix(mine, profiles)
    live, filled = _in_season(mine, profiles, latest)
    still = (
        "Every slot filled." if not empty_slots
        else f"{empty_slots} slot{'' if empty_slots == 1 else 's'} still to draft."
    )
    mix_card = (
        f'<div class="card"><h2>Where the total comes from</h2>'
        f'<p class="sub">Each roster category is one colour and the assets '
        f'inside it step down in shade, biggest first. Hover a segment for the '
        f'asset, click it for the stats behind the score. {escape(still)}</p>'
        f'<div class="mix">{charts.donut_chart(mix, total)}</div></div>'
    )

    head = f"""
<div class="grid2" style="margin-bottom:22px">
  <div class="tile"><div class="label">Manager</div>
    <div class="value"><span class="who">
      {images.avatar("manager", manager, manager, size=38, slot=slot,
                     depth=1, initials=manager)}
      {escape(manager_name(manager))}</span></div></div>
  <div class="tile"><div class="label">Counting total</div>
    <div class="value">{total:,.1f}</div>
    <div class="note">on {latest} · {_season_note(live, filled)}</div></div>
</div>{mix_card}"""
    (out / "team" / f"{_slug(manager)}.html").write_text(
        _page(f"{LEAGUE_ABBR} — {manager_name(manager)}", head + "".join(sections) +
              _profile_payload(profiles), manager,
              managers, depth=1, stamp=stamp, simulated=simulated)
    )


def _uncovered(store, season: str, version) -> list[tuple[str, str, int]]:
    """Rostered league/type pairs the active benchmark cannot score.

    A standing built while a league has no benchmark is not wrong, but it is
    partial, and it looks exactly like a complete one: the managers holding
    those picks are simply lower. Saying so on the page is the difference
    between a season in progress and a season being misreported.
    """
    from whul import benchmarks as benchmark_method

    if version is None:
        return []
    try:
        table = benchmark_method.coverage(store, version.version, season)
    except Exception:  # noqa: BLE001 -- a note on a page must never fail a build
        return []
    if table.empty or "covered" not in table.columns:
        return []
    missing = table[~table["covered"].astype(bool)]
    return [
        (str(row.league), str(row.asset_type), int(row.assets))
        for row in missing.itertuples()
    ]


def _rules_section(rules) -> str:
    """One asset type's rules, collapsed until a reader asks for it."""
    lines = []
    for line in rules.lines:
        if isinstance(line, rulebook.Heading):
            lines.append(f"<li class='rulehead'>{escape(line.text)}</li>")
        else:
            lines.append(f"<li>{escape(line)}</li>")
    notes = "".join(f"<li>{escape(note)}</li>" for note in rules.notes)
    return f"""
<details class="rules" id="{rules.slug}">
  <summary>{escape(rules.title)}</summary>
  <div class="rulebody">
    <p class="sub">{escape(rules.intro)}</p>
    <ul class="rulelist">{"".join(lines)}</ul>
    {f'<ul class="rulenotes">{notes}</ul>' if notes else ""}
  </div>
</details>"""


def _rulebook() -> str:
    """Every asset type's raw scoring, as free text under a heading each.

    Free text and not a table on purpose: the sports do not share a shape. Golf
    is a ladder of thirty finishing positions, baseball is nine counting stats
    and a run estimate, international football is two multipliers over a ceiling.
    Forcing all of that into one grid would mean a grid mostly full of blanks,
    and blanks read as "nothing here" rather than "not applicable".
    """
    return "".join(_rules_section(rules) for rules in rulebook.sections())


#: The four steps, written for somebody who has never seen the data. Nothing
#: here names a file, a feed or a script: a reader who wants to know why their
#: striker is on 63 does not need to know where the number came from, and a
#: reader who does can read the code.
STEPS = (
    ("1. Count what happened",
     "Every sport has its own scoresheet — a touchdown is worth four or six, a "
     "goal three to six depending where the scorer plays, a stage win at a "
     "Masters 1000 two hundred. These are raw points, and they are only "
     "comparable inside one sport."),
    ("2. Put every sport on the same scale",
     "Raw totals are not comparable: a tennis champion collects 2,000 points in "
     "a fortnight and an NHL forward perhaps 250 across a whole season. So each "
     "total is divided by a benchmark for that sport and position and multiplied "
     "by 100. The benchmark is what a genuinely elite season looks like there — "
     "measured across many past seasons by the kind of player who actually gets "
     "drafted, and set at the level only the top one per cent of them reach."),
    ("What 100 means",
     "100 is that elite season. 50 is half of one. Above 100 is not an error and "
     "is not capped — it means a season better than 99 out of 100 draftable ones, "
     "which is what a genuinely great year should look like. Every slot on every "
     "roster is measured this way, so a golfer's 74 and a centre-back's 74 mean "
     "the same thing."),
    ("3. Points stay with whoever owned the slot",
     "A slot is credited with what its occupant earned while it sat there. Trade "
     "a player in March and the points they scored for you in October stay with "
     "you; the manager who receives them starts from the day of the trade."),
    ("4. Best ball — there is nothing to set",
     "Each category counts only its best few slots, and the selection moves on "
     "its own as scores move. There is no lineup to submit and no way to leave "
     "points on your bench."),
)


def _calculator_panel(store, season, version) -> str:
    """The rules, as something a reader can try rather than only read.

    The arithmetic runs in the browser off a spec generated from the scorers'
    own weight tables -- see `whul.site.calculator`. What reaches the page is
    the same dictionaries the pipeline scores with, so the calculator cannot
    drift from the thing it explains.
    """
    from whul.site import calculator

    benchmarks: dict[str, float] = {}
    if version is not None:
        rows = bm.load(store, version.version)
        if not rows.empty:
            benchmarks = dict(
                zip(rows["norm_key"].astype(str),
                    rows["benchmark"].astype(float))
            )
    spec = calculator.payload(benchmarks, version.version if version else "")
    return (
        f'<script type="application/json" id="calcdata">{json.dumps(spec)}</script>'
        '<div class="calculator" id="calcpanel"></div>'
    )


