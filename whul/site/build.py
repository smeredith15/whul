#: Country -> confederation, built once from the table above.
CONFEDERATION_OF = {
    country: shield
    for shield, countries in CONFEDERATIONS.items()
    for country in countries
}


def corner_badge(asset_type: str, category: str, league: str,
                 affiliation: str) -> tuple[str, str] | None:
    """The image that goes bottom-right of this asset's picture.

    ``(directory, filename stem)``, or None where nothing is known to put
    there. Which directory it is follows from what the asset is, so there is
    nothing to choose and nothing to keep in step:

        a team-sport player   his club's crest
        an individual athlete their country's flag
        a club or programme   its league's mark
        an international side its confederation's shield
        an Olympic entry      the rings

    The main picture is always ``asset/<asset id>``. This is only the corner.
    """
    if asset_type == "Team":
        if "Intl" in category:
            shield = CONFEDERATION_OF.get(affiliation.strip())
            return ("shield", shield) if shield else None
        if category == "Olympics":
            return ("shield", "olympics")
        return ("badge", _slug(league)) if league else None
    if category in INDIVIDUAL_CATEGORIES:
        return ("flag", _slug(affiliation)) if affiliation else None
    return ("club", _slug(affiliation)) if affiliation else None


def badge_names(store: Store, season: str, as_of=None) -> dict[str, str]:
    """What to badge each asset with, keyed by asset id.

    The feed's spelling first, the spreadsheet's second -- the same precedence
    the profile line uses, and for the same reason twice over.

    The feed notices a transfer, which the sheet only does when somebody
    remembers. And the feed's name is ESPN's own, so a crest looked up under it
    matches by construction: the sheet said "Los Angeles Clippers" and ESPN
    files them as "LA Clippers", so a perfectly correct name found nothing at
    all. Preferring the feed makes that class of miss impossible wherever the
    feed has an answer, and the sheet stays the answer where it does not --
    every golfer's country, and every league that has not kicked off.

    A club that changes spelling between the two therefore changes the crest's
    filename too. The old file goes stale rather than wrong; the fetch writes
    the new one and nothing points at the old.
    """
    day = as_of or store.scalar(
        "SELECT MAX(as_of) FROM raw_stats WHERE season = ?", (season,)
    )
    from_feed: dict[str, dict] = {}
    if day:
        stats = store.read_stats(season, day)
        if not stats.empty:
            from_feed = {row["asset_id"]: row for row in stats.to_dict("records")}

    rows = store.query(
        "SELECT DISTINCT a.asset_id, a.league, a.norm_key, a.affiliation "
        "FROM roster_slots r "
        "JOIN slot_occupancy o ON o.slot_id = r.slot_id AND o.end_date IS NULL "
        "JOIN assets a ON a.asset_id = o.asset_id "
        "WHERE r.season = ?", (season,),
    )
    out: dict[str, str] = {}
    for row in rows.itertuples():
        who = _identity(
            from_feed.get(row.asset_id, {}), str(row.league or ""),
            str(row.norm_key or ""), str(row.affiliation or ""),
        )
        if who["team"]:
            out[str(row.asset_id)] = who["team"]
    return out


def _affiliation(meta, asset_id: str) -> str:
    """The club the roster says an asset plays for, or an empty string."""
    if asset_id not in getattr(meta, "index", ()):
        return ""
    return str(meta.loc[asset_id, "affiliation"] or "").strip()


def asset_profiles(
    store: Store, season: str, as_of, wanted: set[str], depth: int = 0
) -> dict[str, dict]:
    """Everything the profile window shows, for every asset the page mentions.

    Built once and embedded in the page. On a static site there is nothing to
    fetch from, so a profile has to already be there when it is clicked -- and
    for a few hundred assets that is a smaller payload than one photograph.
    """
    scores = store.query(
        "SELECT asset_id, league_points, scaled_score FROM daily_scores "
        "WHERE season = ? AND as_of = ?",
        (season, str(as_of)),
    ).set_index("asset_id")
    meta = store.query(
        "SELECT asset_id, display_name, league, role, norm_key, affiliation, "
        "asset_type FROM assets"
    ).set_index("asset_id")
    stats = store.read_stats(season, as_of)
    # The roster category, which is what decides whether a corner badge is a
    # club, a flag or a shield. It lives on the slot rather than the asset,
    # since the same country can be a men's and a women's side.
    categories = dict(store.query(
        "SELECT DISTINCT o.asset_id, r.category FROM roster_slots r "
        "JOIN slot_occupancy o ON o.slot_id = r.slot_id AND o.end_date IS NULL "
        "WHERE r.season = ?", (season,),
    ).itertuples(index=False, name=None))

    lines: dict[str, list[tuple[str, str]]] = {}
    finishes: dict[str, list[dict]] = {}
    bonuses: dict[str, list[dict]] = {}
    notes: dict[str, list[str]] = {}
    raw_rows: dict[str, dict] = {}
    panels: dict[str, dict] = {}
    # Built once for the whole day rather than per player: it is a scan of
    # every club's row, and there are fifty footballers asking.
    club_games = _club_games(stats, store.read_club_games(season, as_of))
    if not stats.empty:
        for row in stats.to_dict("records"):
            asset_id = row["asset_id"]
            # What the asset *is*, which is not always what pulled it. NASCAR
            # and Formula 1 arrive as one feed called Motorsports and the row
            # is stored under that name, so the series a driver runs in can
            # only be read off the asset.
            asset_league = (str(meta.loc[asset_id, "league"])
                            if asset_id in meta.index else "")
            finishes[asset_id] = _finish_list(row)
            bonuses[asset_id] = _bonus_list(row)
            notes[asset_id] = _scaling_notes(row)
            lines[asset_id] = _stat_lines(row)
            raw_rows[asset_id] = row
            if str(row.get("league")) == "NFL":
                # On whether the role is a position, not on whether the field
                # is set: a team's `role` arrives as NaN, and NaN is truthy, so
                # testing it sent every club down the player path, which
                # returned nothing and left them on the old table.
                role = str(row.get("role") or "").strip().upper()
                panel = (_nfl_panel(row) if role in NFL_TOP_LINE
                         else _nfl_team_panel(row))
                if panel:
                    panels[asset_id] = panel
            elif str(row.get("league")) == "MLB" and not _has_a_role(row):
                # `not row.get("role")` would be wrong here: a club's role
                # arrives as NaN and NaN is truthy, so every club took the
                # player path. Third time in this file.
                panel = _mlb_team_panel(row)
                if panel:
                    panels[asset_id] = panel
            elif str(row.get("league")) == "MLB" and row.get("role"):
                # By the club, which the row does not carry: a batting line has
                # no team on it, and the roster's own note of who he plays for
                # is the only thing that does.
                panel = _mlb_panel(row, club_games.get(_affiliation(meta, asset_id)))
                if panel:
                    panels[asset_id] = panel
            elif str(row.get("league")) == "NBA" and _has_a_role(row):
                panels[asset_id] = _nba_panel(row)
            elif str(row.get("league")) == "NHL" and _has_a_role(row):
                panels[asset_id] = _nhl_panel(row)
            elif asset_league in team_panels():
                # Basketball, hockey and the five college sports, all scored by
                # counting things. The same branch answers a club with a season
                # behind it and one with nothing, because the table it is built
                # from does not need a row to be read.
                panels[asset_id] = _counted_team_panel(asset_league, row)
            elif asset_league in MOTORSPORT_BOXES:
                panel = _motorsport_panel(row, asset_league)
                if panel:
                    panels[asset_id] = panel
            elif asset_league == "PGA":
                panels[asset_id] = _golf_panel(row)
            elif asset_league in TENNIS_TOURS:
                panels[asset_id] = _tennis_panel(row)
            elif _is_a_club_soccer_player(row):
                panels[asset_id] = _soccer_player_panel(
                    row, club_games,
                    str(meta.loc[asset_id, "league"])
                    if asset_id in meta.index else "")
            elif row.get("sections"):
                panel = _soccer_panel(row)
                if panel:
                    panels[asset_id] = panel

    out: dict[str, dict] = {}
    for asset_id in sorted(wanted):
        if not asset_id or asset_id not in meta.index:
            continue
        info = meta.loc[asset_id]
        name = str(info["display_name"])
        league = str(info["league"])
        badge = images.find("badge", _slug(league))
        if asset_id not in panels:
            empty = _panel_before_a_season(
                league, str(info["asset_type"]), str(info["role"] or ""))
            if empty:
                panels[asset_id] = empty
        who = _identity(
            raw_rows.get(asset_id, {}), league, str(info["norm_key"] or ""),
            str(info["affiliation"] or ""),
        )
        # The feed's spelling of the club, which is what a crest is filed
        # under -- except for an individual athlete, whose corner is a flag and
        # whose identity line is not a country at all: a driver's carries his
        # car number, and `_slug("#1")` was being looked up in the flag
        # directory, so every driver lost his flag to a file called "-1".
        badge_by = (
            str(info["affiliation"] or "")
            if categories.get(asset_id, "") in INDIVIDUAL_CATEGORIES
            and str(info["asset_type"]) != "Team"
            else who["team"]
        )
        corner = corner_badge(
            str(info["asset_type"]), categories.get(asset_id, ""), league,
            badge_by,
        )
        # After the corner, which reads the club's own name and must go on
        # doing so -- the crest is looked up by it.
        first, second = _under_a_team(
            str(info["asset_type"]), league, raw_rows.get(asset_id, {}),
            (who["position"], who["team"]),
        )
        # Text, not markup. These used to be escaped here, which read as
        # defensive and was the opposite: an escaped name went on to be
        # escaped again by the chart that drew it and truncated by the label
        # that shortened it, so St. John's Red Storm reached the page as
        # "St. John&#x27;s Red Storm" and its bar as "St. John&amp;#x27;s
        # Red...". A value that is sometimes markup and sometimes not cannot
        # be handled correctly by anything downstream. So this holds what the
        # thing is called, every use escapes it, and `_profile_payload`
        # escapes the fields the browser writes into innerHTML.
        out[asset_id] = {
            "name": marked_name(name, league),
            # The league only where the identity line above it does not
            # already say so. A club read "Premier League · Champions League ·
            # Premier League · Team", the league twice because this repeated
            # what `_under_a_team` had just said.
            "meta": (str(info["asset_type"]) if first == league
                     else f"{league} · {info['asset_type']}"),
            # Each on its own, as well as in the line the window prints. A
            # table cell shows the position and the club and not the rest, and
            # splitting a formatted string back up to get at them is how the
            # two drift apart.
            "position": first,
            "team": second,
            "group": who["group"],
            # Carried so the tables can badge a name without working out again
            # what this already knows. Two derivations of one rule drift.
            "corner": list(corner) if corner else None,
            # A team's picture is a crest and is fitted rather than cropped;
            # carried for the same reason as the corner, so a table does not
            # have to know what an asset type implies.
            "logo": str(info["asset_type"]) == "Team",
            # Kept apart from `meta` as well as in it: the chart labels a bar
            # with the kind alone, and splitting a formatted string back up to
            # get at it is how the two drift.
            "kind": str(info["asset_type"]),
            "league": league,
            "avatar": images.avatar("asset", asset_id, name, size=52, depth=depth,
                                    badge=corner,
                                    logo=str(info["asset_type"]) == "Team"),
            "badge": (
                f'<img class="badge" src="{"../" * depth}{images.OUT_DIR}/badge/'
                f'{escape(badge.name)}" alt="{escape(league)}">' if badge else ""
            ),
            "raw": f"{float(scores.loc[asset_id, 'league_points']):,.1f}"
                   if asset_id in scores.index else "—",
            "scaled": f"{float(scores.loc[asset_id, 'scaled_score']):,.1f}"
                      if asset_id in scores.index else "—",
            "stats": lines.get(asset_id, []),
            # Where a league has a panel of its own, it replaces the table
            # rather than joining it: the same figures twice, once as boxes and
            # once as rows, is two things to keep in step.
            "panel": panels.get(asset_id),
            "finishes": finishes.get(asset_id, []),
            "bonus": bonuses.get(asset_id, []),
            "notes": notes.get(asset_id, []),
        }
    return out


