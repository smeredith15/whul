def _slug(value: str) -> str:
    return "".join(c if c.isalnum() or c == "-" else "-" for c in value.lower())


#: What the banner says, keyed by what the simulation actually invented. A
#: banner that overstates is a banner nobody reads: once the rosters are real,
#: calling the players placeholders is false on every page.
BANNERS = {
    "everything": (
        "<strong>Simulated data.</strong> These rosters and players are invented "
        "placeholders so the app can be built before the draft is done. Nothing "
        "here is a real result."
    ),
    "scores_only": (
        "<strong>Placeholder scores.</strong> The rosters, players and prices are "
        "real. The scores are invented so the pages can be built before the season "
        "starts — no game has been played yet."
    ),
}


def _page(title: str, body: str, active: str, managers: list[str],
          depth: int = 0, stamp: str = "", simulated: str | bool = False) -> str:
    """One page's HTML. Depth sets how far up the shared assets are."""
    up = "../" * depth
    nav = [("index.html", "Standings"), ("results.html", "Results"),
           ("about.html", "Scoring")]
    current = ' aria-current="page"'
    links = "".join(
        f'<a href="{up}{href}"{current if label == active else ""}>{label}</a>'
        for href, label in nav
    )
    teams = "".join(
        f'<a href="{up}team/{_slug(m)}.html"'
        f'{current if m == active else ""}>{escape(manager_name(m))}</a>'
        for m in managers
    )
    text = BANNERS.get(simulated if isinstance(simulated, str) else "everything")
    banner = f'<div class="banner">{text}</div>' if simulated else ""
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{escape(title)}</title>
<link rel="stylesheet" href="{up}style.css">
</head>
<body>
<div class="wrap">
<header class="masthead">
  <h1><a href="{up}index.html" style="text-decoration:none">{escape(LEAGUE_NAME)}</a></h1>
  <span class="stamp">{escape(stamp)}</span>
  <nav>{links}{teams}</nav>
</header>
{banner}
{body}
<footer>
  Generated by <code>python -m whul.cli site</code>. Scores are season-to-date,
  on a scale where 100 is an elite season for that sport and position.
</footer>
</div>
<script src="{up}app.js"></script>
</body>
</html>
"""


#: Roster categories whose picks are individuals rather than club employees.
#: Their affiliation is a country, and the corner of their picture is a flag.
INDIVIDUAL_CATEGORIES = {"Tennis", "PGA", "Motorsports", "Olympics"}


#: A letter after the name, for the two categories that hold the same countries
#: under the same names. England is rostered in both, and so are France and
#: Spain: two rows reading "England", one above the other, with nothing to say
#: which is which. The league is in the profile window, but a roster is read
#: without clicking anything.
#:
#: Plain text rather than markup, because this name travels into a chart label,
#: a tooltip and a `data-` attribute as well as into a table cell, and a name
#: that is HTML in one of those places is a name that is escaped twice in
#: another.
NAME_MARKS = {"Men's Intl Soccer": "M", "Women's Intl Soccer": "W"}


def marked_name(name: str, league: str) -> str:
    """The display name, told apart from its opposite number where it has one."""
    mark = NAME_MARKS.get(str(league))
    return f"{name} ({mark})" if mark else str(name)


def _under_a_team(asset_type: str, league: str, stats: dict,
                  otherwise: tuple[str, str]) -> tuple[str, str]:
    """The grey line under a club's name, which is never the name again.

    A team's affiliation *is* its own name -- Arsenal plays for Arsenal -- so
    the line that carries a player's position and club carried "Arsenal" under
    "Arsenal" for every one of ninety team assets.

    A soccer club gets something worth the space instead: its domestic league,
    which the roster's own column does not say (a slot reads "Club Soccer Top
    3"), and the continental competition it is in this season, which is the
    difference between a Tuesday in Europe and a season of Saturdays.

    Every other team gets nothing. They are drafted one league at a time and
    the category beside them already says which, so the line would only repeat
    it.
    """
    if asset_type != "Team":
        return otherwise
    if league not in fixtures.SOCCER:
        return "", ""
    # The whole European season rather than the competition it reached
    # furthest in: a club knocked out of the Champions League and into the
    # Europa League played in both, and naming one of them says its Tuesdays
    # were something they were not.
    return league, str(
        stats.get("continental_path") or stats.get("continental") or "").strip()


#: Leagues whose "role" is the same word for everyone in them, and whose tour
#: is the thing worth saying instead. Every tennis player's role is "Singles".
TOUR_AS_POSITION = ("ATP", "WTA")


def _identity(stats: dict, league: str, norm_key: str,
              affiliation: str = "") -> dict[str, str]:
    """What a player is, out of the day's recorded row.

    Three lines, and each is only shown when it says something:

    ``position``  what the player plays -- "F", "Batter", "Driver". The feed
                  calls it ``position`` where it has one and ``role`` where the
                  distinction is the sport itself, and either answers the
                  question a reader is asking.
    ``team``      the club or franchise. This is what tells two players with one
                  surname apart, which no amount of statistics does.
    ``group``     the benchmark group the 0-100 was measured against, which is
                  the position group where a sport has them. Suppressed when it
                  merely repeats the league: an italic line reading "Premier
                  League" under a line reading "Premier League" is furniture.
    """
    def first(*names: str, words_only: bool = False) -> str:
        for name in names:
            value = stats.get(name)
            if value is None or value != value:      # NaN
                continue
            text = str(value).strip()
            if not text or text.lower() in ("nan", "none"):
                continue
            # A position is a word. Golf files a *finishing* position under the
            # same key -- Rory McIlroy read "14.0 · Northern Ireland", which is
            # a place on a leaderboard printed where a role belongs. Skipping
            # the number falls through to the role, which says "Golfer".
            if words_only and text.replace(".", "").replace("-", "").isdigit():
                continue
            return text
        return ""

    group = norm_key.replace("_", " ").strip()

    # A tennis player's role is "Singles", which every tennis player's is, so
    # it distinguishes nobody. The tour does: ATP or WTA is what a reader wants
    # in the place a footballer's position goes.
    position = league if league in TOUR_AS_POSITION \
        else first("position", "role", words_only=True)

    # A driver has no club, and where a footballer's line carries one his can
    # carry his car number -- the sport's own identifier, and the one thing on
    # the car. The hash is what keeps "#1" from reading as a finishing place,
    # which is the other number a motorsport row is full of.
    number = first("car_number", "number", "permanent_number")
    team = f"#{number}" if number else \
        (first("team_name", "team", "club") or affiliation.strip())

    return {
        "position": position,
        # The feed first, then the sheet. The feed is the one that notices a
        # January transfer; the sheet is the one that knows a golfer is Spanish,
        # which no feed here carries at all. Neither covers the other's case, so
        # both are read and the fresher wins where they overlap.
        "team": team,
        "group": "" if group in ("", league) else group,
    }


