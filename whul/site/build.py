#: Which counting stats lead an NFL profile, by the role the player scores in.
#: A quarterback's passing line is three zeroes on a receiver, and a flat list
#: of every column showed exactly that -- nine rows, five of them nothing.
#:
#: `TDS` is not a column. Rushing and receiving touchdowns are one box with two
#: figures, which is safe here and only here: both are worth six, so the single
#: points strip beneath them is exact. It would not be on a quarterback's
#: passing touchdowns, which are worth four -- which is why those lead his row
#: on their own.
NFL_TOP_LINE: dict[str, tuple[str, ...]] = {
    "QB": ("passing_yards", "passing_tds", "interceptions", "rushing_yards"),
    "RB": ("rushing_yards", "receptions", "receiving_yards", "TDS"),
    "WR": ("receptions", "receiving_yards", "rushing_yards", "TDS"),
    "TE": ("receptions", "receiving_yards", "rushing_yards", "TDS"),
}

#: Which touchdown is named first in the shared box, by role -- and the label
#: says so, rather than leaving two numbers either side of a slash for the
#: reader to assign. A back's rushing leads; a receiver's receiving does, the
#: same way round as the rest of his row.
NFL_TD_ORDER: dict[str, tuple[str, str]] = {
    "WR": ("receiving_tds", "rushing_tds"),
    "TE": ("receiving_tds", "rushing_tds"),
}
NFL_TD_SHORT = {"rushing_tds": "Rush", "receiving_tds": "Rec"}

#: Shown even at zero, because zero is the good answer and its absence reads as
#: missing data rather than as a clean season. Everything else empty is dropped:
#: a quarterback has no receptions and saying so four times is noise.
NFL_ALWAYS = ("interceptions", "fumbles_lost")

#: The line for a player whose position nobody has told us yet. It only arises
#: before he has been scored once -- a stat row always says what he plays, and
#: the position is kept on the asset the first time one arrives -- so it is a
#: profile of dashes either way, and these four name every way an NFL player
#: scores rather than guessing at one of the four position lines and drawing a
#: quarterback receiving boxes.
NFL_UNKNOWN_LINE = ("passing_yards", "rushing_yards", "receiving_yards", "TDS")

NFL_BOX_LABELS = {
    "passing_yards": "Pass yds", "passing_tds": "Pass TD",
    "interceptions": "INT", "rushing_yards": "Rush yds",
    "rushing_tds": "Rush TD", "receptions": "Rec",
    "receiving_yards": "Rec yds", "receiving_tds": "Rec TD",
    "fumbles_lost": "Fumbles", "TDS": "TD",
}


def _nfl_box(row: dict, column: str, prefix: str = "",
             keep_zero: bool = False,
             td_order: tuple[str, str] = ("rushing_tds", "receiving_tds"),
             ) -> dict | None:
    """One stat, its count, and what the count is worth.

    The pair is the point. A flat list put `wins 1` directly above
    `pts_reg_wins 2.4` and invited the reader to decide which of the two was
    wrong; a box says the second *is* the first, priced.

    Every figure here is `count x weight` off the scorer's own table, so the
    boxes sum to the points beside them and a profile that does not add up is
    visible rather than plausible.
    """
    from whul.scoring.nfl import PLAYER_WEIGHTS

    # None where the feed put nothing, which for a scored player never happens
    # -- a row carries every column the weight table names, zero included --
    # and for a player nobody has a row for is every column there is. Zero says
    # he played and did none of it; a dash says we do not know, and the two are
    # not the same claim.
    def figure(name: str):
        return _stat_number(row, f"{prefix}{name}")

    dash = "\u2014"
    if column == "TDS":
        first, second = (figure(c) for c in td_order)
        known = [v for v in (first, second) if v is not None]
        count = sum(known) if known else None
        points = None if count is None else count * 6.0
        text = dash if count is None else (
            f"{first or 0:,.0f} / {second or 0:,.0f}")
        label = " / ".join(NFL_TD_SHORT[c] for c in td_order) + " TD"
    else:
        count = figure(column)
        points = None if count is None else count * PLAYER_WEIGHTS.get(column, 0.0)
        text = dash if count is None else f"{count:,.0f}"
    if not count and count is not None and not keep_zero and column not in NFL_ALWAYS:
        return None
    if column != "TDS":
        label = NFL_BOX_LABELS.get(column, _label_for(column))
    return {"label": label,
            # `or 0.0` because a zero count against a negative weight rounds to
            # `-0.0`, which renders as "-0.0" and reads as a penalty nobody
            # took. Negative zero is falsy, so this keeps every real figure.
            "value": text,
            "points": None if points is None else (round(points, 1) or 0.0)}


def _nfl_rest(lead) -> list[str]:
    """The secondary row's columns: whatever the role's own line does not carry.

    The touchdowns are folded into one box wherever they land, so a role whose
    top row has taken them must not be offered them again.
    """
    from whul.scoring.nfl import PLAYER_WEIGHTS

    rest: list[str] = []
    for column in PLAYER_WEIGHTS:
        if column in lead:
            continue
        if column in ("rushing_tds", "receiving_tds"):
            if "TDS" not in lead and "TDS" not in rest:
                rest.append("TDS")
            continue
        rest.append(column)
    return rest


def _nfl_shared_rest(row: dict) -> set[str]:
    """Secondary columns either phase has a figure for.

    The playoff section is the same boxes as the season, which is what makes
    January readable against September without first checking which boxes are
    present. So a box appears in both or in neither, even where one of them is
    a zero. Asked of `_nfl_box` itself rather than of a second copy of its
    emptiness rule, which would be one more thing to keep in step.
    """
    role = str(row.get("role") or row.get("position") or "").upper()
    lead = NFL_TOP_LINE.get(role)
    if lead is None:
        return set()
    order = NFL_TD_ORDER.get(role, ("rushing_tds", "receiving_tds"))
    return {c for c in _nfl_rest(lead)
            if _nfl_box(row, c, "", td_order=order) is not None
            or _nfl_box(row, c, "post_", td_order=order) is not None}


def _nfl_boxes(row: dict, prefix: str = "",
               keep: set | None = None) -> dict | None:
    """An NFL player's season as a top row and a smaller one beneath it.

    The top row is the role's own line and the second is everything else he
    did, which for most players is nothing and is therefore mostly empty. Both
    are built from the same weight table the score is, so nothing here is a
    second opinion about what a yard is worth.
    """
    from whul.scoring.nfl import PLAYER_WEIGHTS

    role = str(row.get("role") or row.get("position") or "").upper()
    lead = NFL_TOP_LINE.get(role)
    if lead is None:
        # A player nobody has a position for, which happens only before he has
        # ever been scored. Refusing here is what left an injured tight end's
        # profile reading "No stat lines recorded for this day yet" four weeks
        # into a season -- the one profile a manager opens to ask exactly that.
        if any(_stat_number(row, f"{prefix}{c}") for c in PLAYER_WEIGHTS):
            return None
        lead = NFL_UNKNOWN_LINE
        role = ""

    # The top row keeps its zeroes. It is the line that makes one profile
    # comparable with the next, and a receiver who happened not to run the ball
    # would otherwise show three boxes where his team-mate shows four.
    order = NFL_TD_ORDER.get(role, ("rushing_tds", "receiving_tds"))
    top = [box for box in
           (_nfl_box(row, c, prefix, keep_zero=True, td_order=order)
            for c in lead) if box]
    secondary = [
        box for box in
        (_nfl_box(row, c, prefix, keep_zero=bool(keep and c in keep),
                  td_order=order)
         for c in _nfl_rest(lead)) if box
    ]
    if not top and not secondary:
        return None
    return {"top": top, "secondary": secondary}


def _nfl_panel(row: dict) -> dict | None:
    """An NFL player's profile: his season in boxes, and January in the same.

    The postseason gets the identical treatment rather than a summary, because
    the question a manager opens a profile to ask is the same one in January as
    in September, and answering it two different ways means reading the layout
    before reading the figures.

    It is absent until there is a postseason, which for the NFL is four months
    of the year showing nothing rather than an empty table saying nothing.
    """
    season = _nfl_boxes(row)
    if season is None:
        return None
    panel: dict = {"season": season}

    def figure(name: str) -> float:
        try:
            return float(row.get(name) or 0)
        except (TypeError, ValueError):
            return 0.0

    # The same heading every other slot carries, built by the same function.
    # Always both figures, and a dash where one is not known: "Games played 3"
    # alone cannot say whether the other fourteen were missed or not yet
    # played, which is the only reason the number is worth a heading -- and the
    # heading is worth keeping even when neither is known, because a profile
    # with no heading reads as a broken page rather than as a player who has
    # not taken the field.
    panel["head"] = _games_head(row)
    if figure("postseason_games"):
        kept = _nfl_shared_rest(row)
        panel["season"] = _nfl_boxes(row, keep=kept) or season
        post = _nfl_boxes(row, prefix="post_", keep=kept)
        if post:
            priced = _playoff_post(row, post)
            post = priced if priced else post
            post["games"] = f"{figure('postseason_games'):,.0f}"
            panel["post"] = post
    return panel


