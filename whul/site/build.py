"""Generate the static site.

The league updates once a day and is read by five people, so the app does not
need a server: the nightly job runs the pipeline, this writes HTML, and
anything that can serve files serves it. That keeps hosting free and removes
the class of failure where the site is down because a process died.

Pages:

* ``index.html``      -- standings, the progression line, the contribution bars
* ``team/<id>.html``  -- one manager's slots, raw and normalized, with the
                         best-ball selection marked
* ``about.html``      -- how a score is arrived at

Every chart is followed by a table view. That is the accessibility floor, and
also the relief the light-mode palette's contrast warning requires.
"""

