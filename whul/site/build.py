#: dict's own order varies between feeds, so without this the same sport reads
#: differently from one day to the next.
HEADLINE = (
    "h", "ab", "hr", "rbi", "bb", "sb", "ip", "so", "sv", "hld",
    "goals", "assists", "matches", "starts", "minutes",
    "wins", "reg_wins", "games_played", "big_wins", "reg_big_wins",
    "point_diff", "run_diff", "conf_wins", "events",
    "passing_yards", "rushing_yards", "receiving_yards", "receptions",
)

#: Where the sport's own shorthand is shorter and clearer than the words.
#: Everywhere else the full label reads better -- "Goals 1" beats "1 G", and
#: G would collide with games anyway.
SHORT = {
    "hr": "HR", "bb": "BB", "so": "K", "sb": "SB", "cs": "CS", "hbp": "HBP",
    "doubles": "2B", "triples": "3B", "sv": "SV", "hld": "HLD", "rbi": "RBI",
}

#: Figures that do not difference. A rate is not a count, so yesterday's
#: subtracted from today's is not what happened today -- it is noise with a
#: plausible magnitude, which is worse than nothing.
NOT_COUNTABLE = {"offense", "defense", "war", "position_points", "advanced_share"}

#: How many figures a day's line carries. It is a summary sitting inside a
#: table cell, not a profile -- the profile window is one click further on and
#: carries everything.
BRIEF = 5


def _countable(row: dict) -> dict[str, float]:
    """The figures in a stat row that a day can be a difference of."""
    out: dict[str, float] = {}
    for column, value in row.items():
        if column in STAT_SKIP or column in NOT_COUNTABLE:
            continue
        # A points column is the score, which the panel shows in its own
        # column. Differencing it would say the same thing twice.
        if column.endswith("_points"):
            continue
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            continue
        if value != value:   # NaN, which is how a feed spells "not this role"
            continue
        out[column] = float(value)
    return out


def _number(value: float) -> str:
    return f"{value:,.0f}" if float(value).is_integer() else f"{value:,.1f}"


def _innings(value: float) -> str:
    """Innings pitched, in the notation every box score uses.

    The feed stores thirds as decimals -- 20.33, 20.67 -- so differencing two
    of them is arithmetic and correct. Printing the result is not: a day's
    5.33 rounds to "5.3", and baseball has no such figure. Two thirds of an
    inning is .2, and a reader who knows that reads .3 as a typo, while one
    who does not reads it as a third of an inning too many.
    """
    outs = round(float(value) * 3)
    return f"{outs // 3}.{outs % 3}"


def _day_line(now: dict, before: dict, comparable: bool = True) -> list[str]:
    """What a player or team did *that day*, not what they have done all year.

    The feeds report season to date, so a day is the difference between two of
    them. Shown cumulatively the line said "Hits 25, Home runs 13" under a
    score that moved by one -- true, and not an answer to what happened.

    Baseball gets its own shorthand because the sport has one and it is
    shorter than the words: a batter's day is 2-for-4, not "Hits 2, At bats 4".
    """
    # A day is a difference, and without both ends there is no difference to
    # take. `raw_stats` reaches back only as far as the first nightly run while
    # `slot_scores` were backfilled, so the earliest listed days have a score
    # to compare and no stats to compare -- and subtracting nothing from a
    # season総 printed a whole year as one day: "19.0 IP, 15 H, 9 K" under a
    # score that moved by four. Better to say nothing than that.
    if not comparable:
        return []
    today = _countable(now)
    delta = {c: today[c] - _countable(before).get(c, 0.0) for c in today}
    delta = {c: v for c, v in delta.items() if abs(v) >= 0.05}
    if not delta:
        return []

    parts: list[str] = []
    if "ip" in delta:
        # A pitching line, and the order is the sport's own: innings, then
        # hits, then the rest. `h` is hits *allowed* here, and put anywhere
        # else it reads as a batter's four hits rather than a pitcher's four
        # given up.
        parts.append(f"{_innings(delta.pop('ip'))} IP")
        if "h" in delta:
            parts.append(f"{_number(delta.pop('h'))} H")
        delta.pop("ab", None)
    else:
        hits, at_bats = delta.pop("h", None), delta.pop("ab", None)
        if at_bats:
            parts.append(f"{_number(hits or 0)}-for-{_number(at_bats)}")
        elif hits:
            parts.append(f"{_number(hits)} H")

    order = {c: i for i, c in enumerate(HEADLINE)}
    for column in sorted(delta, key=lambda c: (order.get(c, len(HEADLINE)), c)):
        value = delta[column]
        parts.append(f"{_number(value)} {SHORT[column]}" if column in SHORT
                     else f"{_label_for(column)} {_number(value)}")
        if len(parts) == BRIEF:
            break
    return parts


def _day_breakdown(
    store: Store, season: str, days: list, managers: list[str],
) -> dict:
    """What each manager's counting slots did on each listed day.

    The progression table gives a manager's total by date and says nothing
    about how it got there. This is the answer to "what happened on the 12th":
    every counting asset that moved since the previous listed day, what it
    added, and the figures behind it -- a statline for a player, a result for
    a team or an individual athlete.

    Keyed on the days the table actually lists rather than every day of the
    season. The table samples to about fifteen rows, so this is bounded by what
    is on screen instead of growing with the year, and the deltas are between
    consecutive *listed* days for the same reason: they are the movements a
    reader can see.
    """
    listed = [str(d) for d in days]
    # Which scale each day was scored against. A benchmark is what every score
    # in its group is divided by, so adopting a new one moves every score in
    # that group at once -- and the panel differences consecutive days, which
    # presents that as a day's performance. Three players were down about a
    # point on the day the September scale was frozen, none of them having
    # kicked a ball; the raw totals were identical and only the divisor moved.
    scales = dict(store.query(
        "SELECT as_of, MAX(benchmark_version) AS version FROM daily_scores "
        "WHERE season = ? GROUP BY as_of", (season,),
    ).itertuples(index=False, name=None))

    # Every slot, benched or not, with what it scored and whether it counted.
    # Asking only for counting rows was how Haaland came to show a whole
    # season's 17.0 in a day: benched on the 9th at 9.69 and counting on the
    # 10th at 17.04, he had no row the day before to difference against, so his
    # entire score read as the day's gain.
    scores: dict[str, dict[str, tuple[bool, float, str]]] = {}
    stats: dict[str, dict[str, dict]] = {}
    for day in listed:
        rows = store.query(
            "SELECT s.asset_id, s.score, s.counts, r.manager_id FROM slot_scores s "
            "JOIN roster_slots r ON r.slot_id = s.slot_id "
            "WHERE s.season = ? AND s.as_of = ?",
            (season, day),
        )
        scores[day] = {
            f"{row.manager_id}|{row.asset_id}": (
                bool(row.counts), float(row.score), str(row.manager_id),
            )
            for row in rows.itertuples()
        }
        frame = store.read_stats(season, day)
        stats[day] = {r["asset_id"]: r for r in frame.to_dict("records")} \
            if not frame.empty else {}

    out: dict[str, dict] = {}
    for index, day in enumerate(listed):
        before = scores.get(listed[index - 1], {}) if index else {}
        totals: dict[str, float] = {}
        was: dict[str, float] = {}
        for key, (counts, score, manager) in scores[day].items():
            totals[manager] = totals.get(manager, 0.0) + (score if counts else 0.0)
            was_counts, was_score, _ = before.get(key, (False, 0.0, ""))
            was[manager] = was.get(manager, 0.0) + (was_score if was_counts else 0.0)
        before_scale = scales.get(listed[index - 1]) if index else None
        rescaled = bool(
            index and before_scale and scales.get(day)
            and scales.get(day) != before_scale
        )
        for manager, total in totals.items():
            out[f"{manager}|{day}"] = {
                "total": round(total, 1),
                "delta": round(total - was[manager], 1) if index else None,
                "since": listed[index - 1] if index else None,
                # Set only where the two days were scored against different
                # scales, which is the one case where a move here is not a
                # performance at all.
                "rescaled": rescaled,
                "movers": [],
            }
        # What each asset did, benched or not. This panel is read to see how a
        # day went, not to account for the total, so the figure against a name
        # is that asset's own change -- whether it was counting makes no
        # difference to what it did, and a bench slot moving in or out is not a
        # performance to report either way.
        #
        # Today's roster only. An asset traded away is no longer this manager's
        # and would otherwise appear as a loss the size of its whole score.
        for key, (counts, score, manager) in scores[day].items():
            if f"{manager}|{day}" not in out:
                continue
            asset_id = key.split("|", 1)[1]
            was_score = before.get(key, (False, 0.0, ""))[1]
            delta = score - was_score
            row = stats[day].get(asset_id, {})
            was = stats.get(listed[index - 1], {}).get(asset_id, {}) if index else {}
            # A playoff or European match moves the score by nothing, because
            # the bonus it feeds is held until the competition finishes. The
            # day it was played would otherwise read as a day off.
            pending, bonus_lines = _bonus_moves(row, was) if index else (0.0, [])
            # The first listed day has nothing before it, so every asset looks
            # like a mover -- and at the season's opening every score is zero,
            # which filled that panel with twelve rows of "+0.0". A zero is a
            # zero whichever day it is on.
            if abs(delta) < 0.05 and not bonus_lines:
                continue
            out[f"{manager}|{day}"]["movers"].append({
                "asset": asset_id,
                "points": round(score, 1),
                "delta": round(delta, 1),
                # What the day added to a bonus nobody has been paid yet, and
                # the matches behind it.
                "pending": pending,
                "pending_line": bonus_lines,
                # Shown quieter rather than left out: a benched player having a
                # big day is worth seeing, and is why a day whose counting total
                # did not move can still be worth opening.
                "counts": counts,
                # Comparable when there is a previous stat row to difference
                # against, or when the asset had no score at all before -- in
                # which case everything on it is new and the total is the day.
                "line": _day_line(row, was, bool(was) or not was_score),
                # Only the finishes that fall in this window. The whole list is
                # what the profile is for; here it would credit a golfer's
                # August to a Tuesday in September.
                "finishes": [
                    f for f in _finish_list(row)
                    if not index or str(f.get("date", "")) > listed[index - 1]
                ][:3],
            })
    for entry in out.values():
        entry["movers"].sort(key=lambda m: -abs(m["delta"]))
        entry["movers"] = entry["movers"][:12]
    # A cell with nothing behind it is not marked clickable, so an entry with
    # no movers is a panel that would open empty.
    return {key: entry for key, entry in out.items() if entry["movers"]}


def _table_view(
    summary: str, header: list[str], rows: list[list[str]],
    columns: list[str] | None = None,
    breakdown: list[list[str]] | None = None,
) -> str:
    """A chart's values as a table -- the readable-without-hover fallback.

    ``columns`` names the per-manager columns in order, so hiding a manager in
    the key hides them here too: a reader filtering the chart means the table
    as well, and a table still listing someone the chart has dropped is the
    kind of half-applied filter that gets read as a bug.
    """
    head = "".join(
        f"<th class='num'>{escape(h)}</th>" if i else f"<th>{escape(h)}</th>"
        for i, h in enumerate(header)
    )
    # A cell that can be opened says so with a key, and only where there is
    # something behind it. Marking every cell would promise a breakdown for
    # days nothing moved on, which is a click that opens an empty panel.
    keys = breakdown or []
    body = "".join(
        "<tr>" + "".join(
            (f"<td class='num'>{c}</td>" if not (
                r < len(keys) and i - 1 < len(keys[r]) and keys[r][i - 1]
            ) else
             f"<td class='num'><button class='daycell' "
             f"data-day=\"{escape(keys[r][i - 1])}\">{c}</button></td>")
            if i else f"<td>{c}</td>"
            for i, c in enumerate(row)
        ) + "</tr>"
        for r, row in enumerate(rows)
    )
    named = (
        f' data-columns="{escape(json.dumps(columns))}"' if columns else ""
    )
    return (
        f"<details class='tableview'><summary>{escape(summary)}</summary>"
        f"<table{named}><thead><tr>{head}</tr></thead>"
        f"<tbody>{body}</tbody></table></details>"
    )


def build(
    store: Store,
    season: str,
    out: Path | None = None,
    as_of: date | None = None,
) -> dict:
    """Write the whole site. Returns what it wrote, for the CLI to report."""
    out = Path(out or DEFAULT_OUT)

    progression = pipeline.progression(store, season)
    if progression.empty:
        raise ValueError(_why_no_standings(store, season))

    # Only once there is something to write. Creating it first left an empty
    # `team/` behind on every failed build, which a local server then served as
    # a directory listing -- a site that looks built and is not.
    (out / "team").mkdir(parents=True, exist_ok=True)

    latest = as_of or progression["as_of"].max()
    today = progression[progression["as_of"] == latest].sort_values("rank")
    managers = sorted(progression["manager_id"].unique())
    slotted = [(manager_name(m), theme.series_index(managers, m) + 1) for m in managers]
    simulated = store.scalar(
        "SELECT key FROM admin_overrides WHERE scope = 'simulation' AND season = ? "
        "ORDER BY set_at DESC LIMIT 1",
        (season,),
    ) or False
    version = bm.active_version(store, season)
    stamp = f"{season} · through {latest}"

    bars = pipeline.contributions(store, season, latest)
    counting = bars[bars["counts"] == 1] if not bars.empty else bars
    slot_counts = (
        counting.groupby("manager_id").size().to_dict() if not counting.empty else {}
    )

    (out / "style.css").write_text(theme.STYLESHEET)
    (out / "app.js").write_text(charts.SCRIPT)
    photos = images.copy_all(out)

    rostered = set(bars["asset_id"].dropna()) if not bars.empty else set()
    profiles = asset_profiles(store, season, latest, rostered)
    deep_profiles = asset_profiles(store, season, latest, rostered, depth=1)

    _write_index(out, season, today, progression, bars, managers, slotted,
                 latest, stamp, simulated, profiles, store)
    for manager in managers:
        _write_team(out, manager, managers, bars, store, season, latest, stamp,
                    simulated, deep_profiles)
    _write_about(out, managers, stamp, simulated, version,
                 _uncovered(store, season, version), store=store)

    return {
        "out": str(out),
        "season": season,
        "as_of": str(latest),
        "pages": 2 + len(managers),
        "managers": len(managers),
        "days": int(progression["as_of"].nunique()),
        "simulated": simulated,
        "photos": photos,
        "profiles": len(profiles),
    }


def _why_no_standings(store, season: str) -> str:
    """Which link in the chain is missing, rather than that the chain is.

    Every step depends on the one before, so "no standings" is the symptom of
    four different problems. Naming the first one that is actually missing is
    the difference between a message and an instruction.
    """
    from whul.store import benchmarks as bm
    from whul.store.db import missing_database_note

    lines = [f"No standings for {season}, so there is nothing to build yet."]

    # Before any of the four: is there a database at all? An empty one answers
    # every question below with zero, so without this the message names the
    # first missing link in a chain that was never there.
    note = missing_database_note(store)
    if note:
        return "\n".join(lines) + "\n" + note

    rostered = store.scalar(
        "SELECT COUNT(*) FROM slot_occupancy o "
        "JOIN roster_slots s ON s.slot_id = o.slot_id WHERE s.season = ?",
        (season,),
    ) or 0
    scores = store.scalar(
        "SELECT COUNT(*) FROM daily_scores WHERE season = ?", (season,)
    ) or 0
    frozen = bm.active_version(store, season)

    if not rostered:
        lines.append(
            f"  Nothing is rostered in {season}. Import the draft: "
            f"`python -m whul.cli import-rosters --write --season {season}`"
        )
    elif frozen is None:
        lines.append(
            f"  {rostered} slots are filled, but no benchmark version is frozen "
            f"for {season}, so nothing can be placed on the 0-100 scale.\n"
            f"  `python -m whul.cli benchmarks versions`, then "
            f"`benchmarks freeze <version>`."
        )
    elif not scores:
        lines.append(
            f"  Benchmark {frozen.version} is frozen and {rostered} slots are "
            f"filled, but no results have been recorded.\n"
            f"  `python -m whul.cli ingest --season {season}`"
        )
    else:
        lines.append(
            f"  {scores} scores are recorded but no day has been rolled up.\n"
            f"  `python -m whul.cli rollup --season {season}`"
        )
    lines.append(
        f"  For a placeholder league instead: `python -m whul.cli simulate`."
    )
    return "\n".join(lines)


def _slot_rows(bars: pd.DataFrame, managers: list[str]) -> tuple[list, dict, dict]:
    """Rank each manager's slots within a category, so a row compares like with like.

    Row "NFL 1" is every manager's best NFL slot, "NFL 2" their second, and so
    on. Ranking rather than using the stored slot index matters because a slot
    index is arbitrary -- best ball reorders them constantly -- so comparing
    slot 1 to slot 1 would compare nothing in particular.
    """
    order = []
    seen: set[str] = set()
    for group in active_slots(ALL_SLOTS):
        if group.category not in seen:
            seen.add(group.category)
            order.append(group.category)

    depth = {}
    for group in active_slots(ALL_SLOTS):
        depth[group.category] = depth.get(group.category, 0) + group.starters

    values: dict[tuple[str, str], tuple[float, str, str]] = {}
    counting = bars[bars["counts"] == 1] if not bars.empty else bars
    for manager in managers:
        mine = counting[counting["manager_id"] == manager] if not counting.empty else counting
        for category in order:
            block = mine[mine["category"] == category] if not mine.empty else mine
            # An undrafted slot has no score to rank and no bar to draw, so
            # it is dropped here -- the row still exists on the chart, it just
            # has nothing in it for this manager.
            if not block.empty:
                block = block[block["asset_id"].notna() & (block["asset_id"] != "")]
            ranked = block.sort_values("score", ascending=False) if not block.empty else block
            for rank, row in enumerate(ranked.itertuples(), start=1):
                values[(manager_name(manager), f"{category} {rank}")] = (
                    float(row.score), str(row.asset_id or ""), ""
                )

    # The key stays fully qualified so two categories cannot collide, but the
    # row shows only its rank -- the category is already the run's heading, and
    # repeating it eight times is eight lines of the same words.
    rows = [
        (category, f"{category} {rank}", f"#{rank}")
        for category in order
        for rank in range(1, depth.get(category, 0) + 1)
    ]
    return rows, values, depth


#: What a harvested schedule calls the part of the season a game is in. These
#: are the feed's own codes and they are not competitions: "REG" under a
#: fixture says nothing a reader wants, and the two that do say something are
#: worth spelling out.
SEASON_TYPES = {"REG": "", "REG1": "", "1": "", "2": "",
                "POST": "Playoffs", "3": "Playoffs", "PRE": "Preseason"}


def _board_label(entry: dict) -> str:
    """What competition a fixture is in, or nothing where that adds nothing.

    A club plays in five competitions and which one it is changes what the
    fixture means. Everywhere else the competition is the league, and the feed
    fills the field with a season-type code instead -- so the league's own name
    stands in, and a code that says only "this is the regular season" is
    dropped.
    """
    label = str(entry.get("competition") or "").strip()
    label = SEASON_TYPES.get(label.upper(), label)
    feed = str(entry.get("feed") or "")
    if label:
        return label
    # A feed named for a league can speak for itself; "Flashscore/1" cannot.
    return "" if feed.startswith("Flashscore/") else feed


def _holder(asset_id: str, profile: dict | None, manager: str, slot: int) -> str:
    """One drafted asset under the side it plays for: a face and an owner.

    A picture and two letters rather than a name, because a side can have six
    of them and a column of full names is a column, not a line. The name is on
    the tooltip and the click opens the profile, which is where a reader who
    wants more goes anyway.
    """
    name = profile["name"] if profile else asset_id
    corner = (profile or {}).get("corner")
    corner = tuple(corner) if corner else None
    face = images.avatar(
        "asset", asset_id, name, size=22, badge=corner,
        logo=bool((profile or {}).get("logo")),
    )
    return (
        f'<button class="assetlink holder" data-asset="{escape(asset_id)}" '
        f'type="button" style="--own: var(--series-{slot})" '
        f'title="{escape(f"{name} — {manager_name(manager)}")}">'
        f'{face}<b>{escape(manager)}</b></button>'
    )


def _board_side(side: dict, profiles: dict, owners: dict, slots: dict) -> str:
    holders = "".join(
        _holder(asset, profiles.get(asset), owners.get(asset, ""),
                slots.get(owners.get(asset, ""), 1))
        for asset in side["assets"]
    )
    # No empty div where a side has nobody in it: it is a margin and a line of
    # height under a name, and half the ties on the board have one.
    return (
        f'<div class="side">'
        f'<div class="sidename">{escape(side["name"])}</div>'
        + (f'<div class="holders">{holders}</div>' if holders else "")
        + '</div>'
    )


def _fixture_board(store, season, latest, profiles, managers) -> str:
    """Every upcoming fixture with a drafted asset in it, both sides named.

    The roster pages say what one asset plays next. This says who is playing
    whom -- and a tie with assets on both sides, which no roster page can show,
    is the row this exists for.
    """
    entries = fixtures.board(store, season, latest)
    if not entries:
        return ""
    owners = fixtures.owners(store, season)
    slots = {m: theme.series_index(managers, m) + 1 for m in managers}

    chips = "".join(
        f'<button class="chip ownerchip" data-filter="owner" '
        f'data-value="{escape(m)}" aria-pressed="false">'
        f'<i class="swatch" style="background: var(--series-{slots[m]})"></i>'
        f'{escape(manager_name(m))}</button>'
        for m in managers
    )

    days: dict[str, list[str]] = {}
    day_owners: dict[str, set[str]] = {}
    for entry in entries:
        blocks_here = [
            _board_side(side, profiles, owners, slots) for side in entry["sides"]
        ]
        # The "v" between them, in the DOM order the two columns are read in.
        # Appended after both, it lands in the third grid cell and the row
        # reads "Bayern Munich  Bodo/Glimt v", which is a sentence about
        # nothing.
        sides = ('<div class="v">v</div>'.join(blocks_here)
                 if len(blocks_here) > 1 else blocks_here[0])
        middle = ""
        label = "" if entry["event"] else _board_label(entry)
        held = " ".join(entry["owners"])
        kind = " event" if entry["event"] else ""
        # Padded with spaces so a filter can test for " SS " and not match
        # a manager whose id is a substring of another's.
        comp = f'<div class="comp">{escape(label)}</div>' if label else ""
        days.setdefault(entry["date"], []).append(
            f'<div class="tie{kind}" data-owners=" {escape(held)} ">'
            f'{sides}{middle}{comp}</div>'
        )
        day_owners.setdefault(entry["date"], set()).update(entry["owners"])

    blocks = []
    for day, ties in days.items():
        try:
            when = date.fromisoformat(day)
            heading = f"{when:%A} {when.day} {when:%B}"
        except ValueError:
            heading = day
        # Open, all of them. A week is small enough to read down, and the
        # `details` is here so a reader can shut a day rather than so the page
        # can start out hiding six of them.
        held = escape(" ".join(sorted(day_owners[day])))
        blocks.append(
            f'<details class="boardday" open data-owners=" {held} ">'
            f'<summary>{escape(heading)}'
            f'<span class="count">{len(ties)}</span></summary>'
            f'{"".join(ties)}</details>'
        )

    return f"""
<div class="card" id="fixtures">
  <h2>Who plays whom</h2>
  <p class="sub">The next {fixtures.BOARD_DAYS} days, every fixture with a
    drafted asset in it, both sides named. The faces under each side are the
    assets somebody holds, badged with their owner; click one for its profile.
    Pick an owner to see only the fixtures they have somebody in. Anything
    further out is on the roster pages, in each asset's own Next column.</p>
  <div class="chips" role="group" aria-label="Filter by owner">{chips}</div>
  <div class="board">{"".join(blocks)}</div>
  <p class="sub board-empty" hidden>No upcoming fixture has one of theirs in
    it.</p>
</div>
"""


def _write_index(out, season, today, progression, bars, managers, slotted,
                 latest, stamp, simulated, profiles, store) -> None:
    leader = today.iloc[0]
    margin = float(today.iloc[0]["total"] - today.iloc[1]["total"]) if len(today) > 1 else 0.0

    # Who has gained most in the last week -- the standings say who is ahead,
    # this says who is coming. A ceiling nobody approaches said neither.
    week = sorted(progression["as_of"].unique())
    earlier = week[max(0, len(week) - 8)]
    gains = {}
    for manager in managers:
        run = progression[progression["manager_id"] == manager].set_index("as_of")
        if latest in run.index and earlier in run.index:
            gains[manager] = float(run.loc[latest, "total"] - run.loc[earlier, "total"])
    riser, gain = max(gains.items(), key=lambda kv: kv[1]) if gains else ("—", 0.0)

    counting = bars[bars["counts"] == 1] if not bars.empty else bars
    mvps = {}
    for manager in managers:
        mine = counting[counting["manager_id"] == manager] if not counting.empty else counting
        if not mine.empty:
            mine = mine[mine["asset_id"].notna() & (mine["asset_id"] != "")]
        if mine.empty:
            continue
        best = mine.sort_values("score", ascending=False).iloc[0]
        asset_id = str(best["asset_id"] or "")
        profile = profiles.get(asset_id)
        name = profile["name"] if profile else asset_id or "—"
        corner = (profile or {}).get("corner")
        corner = tuple(corner) if corner else None
        is_logo = bool((profile or {}).get("logo"))
        mvps[manager] = (
            f'<button class="assetlink" type="button" data-asset="{escape(asset_id)}">'
            f'<span class="who">'
            f"{images.avatar('asset', asset_id, name, size=26, badge=corner, logo=is_logo)}"
            f'<span><span class="nm">{name}</span> '
            f'<span style="color:var(--muted)">{best["category"]} · '
            f'{float(best["score"]):,.1f}</span></span></span></button>'
        )

    tiles = f"""
<div class="grid2" style="margin-bottom:22px">
  <div class="tile"><div class="label">Leader</div>
    <div class="value">{escape(manager_name(str(leader['manager_id'])))}</div>
    <div class="note">{leader['total']:,.1f} points, {margin:,.1f} clear</div></div>
  <div class="tile"><div class="label">Biggest riser this week</div>
    <div class="value">{escape(manager_name(str(riser)))}</div>
    <div class="note">+{gain:,.1f} in the last 7 days</div></div>
  <div class="tile"><div class="label">Season</div>
    <div class="value">{escape(season)}</div>
    <div class="note">through {latest}</div></div>
</div>"""

    days = sorted(progression["as_of"].unique())
    series = []
    for (manager, slot), key in zip(slotted, managers):
        run = progression[progression["manager_id"] == key].set_index("as_of")
        series.append(charts.Series(
            name=manager, slot=slot,
            values=[float(run.loc[d, "total"]) if d in run.index else 0.0 for d in days],
        ))

    sampled = days[:: max(1, len(days) // 14)] or days
    if days[-1] not in sampled:
        sampled.append(days[-1])
    breakdown = _day_breakdown(store, season, sampled, managers)
    # Newest first. The chart reads left to right because a line has to, but a
    # table is read from the top, and what a reader wants first is what
    # happened last. The deltas are still computed forwards -- reversing the
    # rows must not turn "since the 5th" into "since the 7th".
    listed = list(reversed(sampled))
    progression_rows = [
        [str(d)] + [f"{s.values[days.index(d)]:,.1f}" for s in series] for d in listed
    ]
    # One key per cell, empty where nothing moved. Built against the same
    # manager order the columns are in, so a cell and its panel cannot drift.
    progression_keys = [
        [(f"{key}|{d}" if f"{key}|{d}" in breakdown else "") for key in managers]
        for d in listed
    ]

    slot_rows, values, slot_depth = _slot_rows(bars, managers)
    # Name each bar's asset, so the tooltip and the table both read as people.
    # The kind rides along, which is what lets a bar say "Arsenal Team" rather
    # than "Club Soccer Top 3 1".
    for key, (score, asset_id, _) in list(values.items()):
        profile = profiles.get(asset_id)
        values[key] = (
            score, asset_id,
            profile["name"] if profile else "",
            profile.get("kind", "") if profile else "",
        )
    bar_rows = [
        [key] + [
            (f"{values[(m, key)][0]:,.1f}" if (m, key) in values else "—")
            for m, _ in slotted
        ]
        for _, key, _ in slot_rows
    ]

    body = f"""
{tiles}
<div class="card">
  <h2>Standings</h2>
  <p class="sub">Season-to-date, best ball: each manager's counting slots only.
    A superscript is what a playoff or European run has earned that is not in
    the score yet, held until that competition finishes. The bench is what best
    ball is not counting, and never will. Click a name to see how a score was
    arrived at.</p>
  {_standings_table(today, mvps, managers,
                    pipeline.bench_by_manager(store, season, latest),
                    pipeline.held_by_manager(store, season, latest))}
</div>

<div class="card">
  <h2>Progression</h2>
  <p class="sub">Total score by day. Hover for every manager on a given date.</p>
  {charts.legend(slotted, filterable=True)}
  {charts.progression_chart(days, series)}
  {_table_view("Show as a table", ["Date"] + [s.name for s in series],
               progression_rows, columns=[s.name for s in series],
               breakdown=progression_keys)}
  <p class="sub">Click any figure in the table for the day it came from.</p>
</div>

{_fixture_board(store, season, latest, profiles, managers)}

{_profile_payload(profiles)}
{_day_payload(breakdown)}
"""
    (out / "index.html").write_text(
        _page(f"{LEAGUE_ABBR} — Standings", body, "Standings", managers,
              stamp=stamp, simulated=simulated)
    )

    # --- results ------------------------------------------------------------
    # The bar chart moves here and the progression is copied. Copied rather
    # than moved because the standings page is what someone opens to see who is
    # winning, and the line is the shape of that; the bars are the detail
    # underneath it, which is what this page is for.
    progression_figure = _figure(
        "progression", "Progression",
        "Total score by day. Hover for every manager on a given date.",
        f"{charts.legend(slotted, filterable=True)}"
        f"{charts.progression_chart(days, series)}"
        + _table_view("Show as a table", ["Date"] + [s.name for s in series],
                      progression_rows, columns=[s.name for s in series],
                      breakdown=progression_keys),
    )
    slots_figure = _figure(
        "slots", "Every counting slot",
        "One section per league, each collapsible. A manager's slots sit "
        "together in their own colour, ranked best first, so a category reads "
        "as a block. Every bar is a single normalized score, so any two are "
        "directly comparable. Click a manager in the key to hide them; click a "
        "bar for the asset behind it.",
        f"{charts.legend(slotted, filterable=True)}"
        f"{charts.slot_sections(slot_rows, slotted, values, depth=slot_depth)}"
        + _table_view("Show as a table", ["Slot"] + [m for m, _ in slotted],
                      bar_rows, columns=[m for m, _ in slotted]),
    )
    table_figure = _figure(
        "everyone", "Every scored asset",
        "Best first, on the normalized scale -- the only figure comparable "
        "across leagues. Filter by kind or league; the filters combine, and "
        "the table at the top re-totals as you go, so filtering to one league "
        "says who is winning it. Click a name for the stats behind the score.",
        _results_table(bars, profiles, managers),
    )
    feeds_figure = _figure(
        "feeds", "Where the numbers came from",
        "Every league this roster holds, and what its feed last did. A league "
        "scoring nothing because its season has not opened and one scoring "
        "nothing because its feed broke look identical in the standings -- a "
        "column of zeroes -- and they need opposite responses.",
        _feed_table(_feed_rows(store, season, latest), latest),
        open_=False,
    )
    results_body = (
        _figure_index([("progression", "Progression"),
                       ("slots", "Every counting slot"),
                       ("everyone", "Every scored asset"),
                       ("feeds", "Where the numbers came from")])
        + progression_figure + slots_figure + table_figure + feeds_figure
        + _profile_payload(profiles) + _day_payload(breakdown)
    )
    (out / "results.html").write_text(
        _page(f"{LEAGUE_ABBR} — Results", results_body, "Results", managers,
              stamp=stamp, simulated=simulated)
    )


def _fixture_cell(fixture: dict | None) -> str:
    """What this asset plays next, small, between its name and its score.

    Two shapes. A fixture is a date and an opponent; a tour event is a date and
    a name, because a golfer and a driver turn up to a field rather than to
    somebody. The second is why the cell does not simply always say "vs".

    Empty where nothing is known, and empty deliberately: a league between
    seasons has nothing to play next, and filling that with a guess would make
    the column untrustworthy for the leagues where it is right.
    """
    if not fixture:
        return "<td class='fixture'></td>"
    try:
        when = date.fromisoformat(str(fixture["date"]))
        day = f"{when:%b} {when.day}"
    except (TypeError, ValueError):
        day = str(fixture.get("date", ""))
    against = str(fixture.get("opponent", ""))
    competition = str(fixture.get("competition", ""))
    if not against and competition:
        # A tour event: a field rather than an opponent. "vs" would be a
        # sentence about nobody, so the event's own name takes the slot the
        # opponent has everywhere else.
        full = f"{day} \u00b7 {competition}"
        return (
            f"<td class='fixture event' title=\"{escape(full)}\">"
            f"<span class='when'>{escape(day)}</span>"
            f"<span class='against'>{escape(competition)}</span></td>"
        )
    versus = "vs" if fixture.get("home") else "at"
    badge = str(fixture.get("badge", ""))
    full = f"{day} {versus} {against}" + (f" ({competition})" if badge else "")
    # The opponent is its own element so a narrow screen can break the line
    # there rather than truncating -- a fixture cut to "Sep 20 vs New Or..."
    # has lost the only part anybody reads it for.
    mark = (f"<span class='comp' title=\"{escape(str(fixture.get('competition','')))}\">"
            f"{escape(badge)}</span>") if badge else ""
    return (
        f"<td class='fixture' title=\"{escape(full)}\">"
        f"<span class='when'>{escape(day)}</span>"
        f"<span class='against'><span class='versus'>{escape(versus)}</span> "
        f"{escape(against)}</span>{mark}</td>"
    )


def _write_team(out, manager, managers, bars, store, season, latest, stamp,
                simulated, profiles) -> None:
    """One manager's roster: every slot, with the normalized score it is worth.

    The raw score and the stat lines behind it live in the profile window
    rather than in the table -- there are sixty slots, and a column of raw
    numbers on a scale that differs per league compares nothing to anything.
    """
    mine = bars[bars["manager_id"] == manager] if not bars.empty else bars
    raw = store.query(
        "SELECT asset_id, league_points, scaled_score FROM daily_scores "
        "WHERE season = ? AND as_of = ?",
        (season, str(latest)),
    ).set_index("asset_id")
    upcoming = fixtures.by_asset(store, season, latest)

    sections = []
    total = 0.0
    empty_slots = 0
    for asset_type in ("Player", "Team"):
        rows = []
        block = mine[mine["asset_type"] == asset_type] if not mine.empty else mine
        if block.empty:
            continue
        for category in sorted(block["category"].unique()):
            for row in block[block["category"] == category].sort_values(
                "score", ascending=False
            ).itertuples():
                asset = str(row.asset_id or "")
                # An undrafted slot is shown, not skipped. It is a slot the
                # manager still has to fill, and hiding it would make a roster
                # with a hole look complete.
                if not asset:
                    empty_slots += 1
                    rows.append(
                        f"<tr class='empty'>"
                        f"<td class='slotname'>{escape(category)}</td>"
                        f"<td class='undrafted'>Undrafted</td>"
                        f"<td class='fixture'></td>"
                        f"<td class='num'>—</td></tr>"
                    )
                    continue
                profile = profiles.get(asset)
                name = profile["name"] if profile else asset
                scaled = float(raw.loc[asset, "scaled_score"]) if asset in raw.index else 0.0
                counts = bool(row.counts)
                total += float(row.score) if counts else 0.0
                # A benched slot's score is struck through rather than hidden:
                # it is what the slot would be worth, and seeing it is how a
                # manager knows how close the bench is to the cut.
                value = (
                    f"{scaled:,.1f}" if counts
                    else f'<span class="struck">{scaled:,.1f}</span>'
                )
                rows.append(
                    f"<tr class='{'' if counts else 'bench'}'>"
                    f"<td class='slotname'>{escape(category)}</td>"
                    f"<td>{_asset_button(asset, name, counts, depth=1, profile=profile)}</td>"
                    f"{_fixture_cell(upcoming.get(asset))}"
                    f"<td class='num'>{value}</td></tr>"
                )
        sections.append(
            f"<div class='card'><h2>{asset_type}s</h2>"
            f"<p class='sub'>Normalized score, where 100 is the 99th percentile of a "
            f"draftable pool. Benched slots are struck through. Click a name for the "
            f"raw stats behind the score.</p>"
            "<table><thead><tr><th>Category</th><th>Asset</th>"
            "<th class='fixture'>Next</th>"
            "<th class='num'>Normalized</th></tr></thead>"
            f"<tbody>{''.join(rows)}</tbody></table></div>"
        )

    slot = theme.series_index(managers, manager) + 1

    # The count of unfilled slots used to be a tile of its own. It is one
    # number that changes a handful of times a season, and it sat beside two
    # others in the space where the interesting question is which parts of the
    # roster are carrying the total. The count keeps its place in the sentence
    # under the ring, where it is still read and no longer costs a third of the
    # header.
    mix = _counting_mix(mine, profiles)
    live, filled = _in_season(mine, profiles, latest)
    still = (
        "Every slot filled." if not empty_slots
        else f"{empty_slots} slot{'' if empty_slots == 1 else 's'} still to draft."
    )
    mix_card = (
        f'<div class="card"><h2>Where the total comes from</h2>'
        f'<p class="sub">Each roster category is one colour and the assets '
        f'inside it step down in shade, biggest first. Hover a segment for the '
        f'asset, click it for the stats behind the score. {escape(still)}</p>'
        f'<div class="mix">{charts.donut_chart(mix, total)}</div></div>'
    )

    head = f"""
<div class="grid2" style="margin-bottom:22px">
  <div class="tile"><div class="label">Manager</div>
    <div class="value"><span class="who">
      {images.avatar("manager", manager, manager, size=38, slot=slot,
                     depth=1, initials=manager)}
      {escape(manager_name(manager))}</span></div></div>
  <div class="tile"><div class="label">Counting total</div>
    <div class="value">{total:,.1f}</div>
    <div class="note">on {latest} · {_season_note(live, filled)}</div></div>
</div>{mix_card}"""
    (out / "team" / f"{_slug(manager)}.html").write_text(
        _page(f"{LEAGUE_ABBR} — {manager_name(manager)}", head + "".join(sections) +
              _profile_payload(profiles), manager,
              managers, depth=1, stamp=stamp, simulated=simulated)
    )


def _uncovered(store, season: str, version) -> list[tuple[str, str, int]]:
    """Rostered league/type pairs the active benchmark cannot score.

    A standing built while a league has no benchmark is not wrong, but it is
    partial, and it looks exactly like a complete one: the managers holding
    those picks are simply lower. Saying so on the page is the difference
    between a season in progress and a season being misreported.
    """
    from whul import benchmarks as benchmark_method

    if version is None:
        return []
    try:
        table = benchmark_method.coverage(store, version.version, season)
    except Exception:  # noqa: BLE001 -- a note on a page must never fail a build
        return []
    if table.empty or "covered" not in table.columns:
        return []
    missing = table[~table["covered"].astype(bool)]
    return [
        (str(row.league), str(row.asset_type), int(row.assets))
        for row in missing.itertuples()
    ]


def _rules_section(rules) -> str:
    """One asset type's rules, collapsed until a reader asks for it."""
    lines = []
    for line in rules.lines:
        if isinstance(line, rulebook.Heading):
            lines.append(f"<li class='rulehead'>{escape(line.text)}</li>")
        else:
            lines.append(f"<li>{escape(line)}</li>")
    notes = "".join(f"<li>{escape(note)}</li>" for note in rules.notes)
    return f"""
<details class="rules" id="{rules.slug}">
  <summary>{escape(rules.title)}</summary>
  <div class="rulebody">
    <p class="sub">{escape(rules.intro)}</p>
    <ul class="rulelist">{"".join(lines)}</ul>
    {f'<ul class="rulenotes">{notes}</ul>' if notes else ""}
  </div>
</details>"""


def _rulebook() -> str:
    """Every asset type's raw scoring, as free text under a heading each.

    Free text and not a table on purpose: the sports do not share a shape. Golf
    is a ladder of thirty finishing positions, baseball is nine counting stats
    and a run estimate, international football is two multipliers over a ceiling.
    Forcing all of that into one grid would mean a grid mostly full of blanks,
    and blanks read as "nothing here" rather than "not applicable".
    """
    return "".join(_rules_section(rules) for rules in rulebook.sections())


#: The four steps, written for somebody who has never seen the data. Nothing
#: here names a file, a feed or a script: a reader who wants to know why their
#: striker is on 63 does not need to know where the number came from, and a
#: reader who does can read the code.
STEPS = (
    ("1. Count what happened",
     "Every sport has its own scoresheet — a touchdown is worth four or six, a "
     "goal three to six depending where the scorer plays, a stage win at a "
     "Masters 1000 two hundred. These are raw points, and they are only "
     "comparable inside one sport."),
    ("2. Put every sport on the same scale",
     "Raw totals are not comparable: a tennis champion collects 2,000 points in "
     "a fortnight and an NHL forward perhaps 250 across a whole season. So each "
     "total is divided by a benchmark for that sport and position and multiplied "
     "by 100. The benchmark is what a genuinely elite season looks like there — "
     "measured across many past seasons by the kind of player who actually gets "
     "drafted, and set at the level only the top one per cent of them reach."),
    ("What 100 means",
     "100 is that elite season. 50 is half of one. Above 100 is not an error and "
     "is not capped — it means a season better than 99 out of 100 draftable ones, "
     "which is what a genuinely great year should look like. Every slot on every "
     "roster is measured this way, so a golfer's 74 and a centre-back's 74 mean "
     "the same thing."),
    ("3. Points stay with whoever owned the slot",
     "A slot is credited with what its occupant earned while it sat there. Trade "
     "a player in March and the points they scored for you in October stay with "
     "you; the manager who receives them starts from the day of the trade."),
    ("4. Best ball — there is nothing to set",
     "Each category counts only its best few slots, and the selection moves on "
     "its own as scores move. There is no lineup to submit and no way to leave "
     "points on your bench."),
)


def _calculator_panel(store, season, version) -> str:
    """The rules, as something a reader can try rather than only read.

    The arithmetic runs in the browser off a spec generated from the scorers'
    own weight tables -- see `whul.site.calculator`. What reaches the page is
    the same dictionaries the pipeline scores with, so the calculator cannot
    drift from the thing it explains.
    """
    from whul.site import calculator

    benchmarks: dict[str, float] = {}
    if version is not None:
        rows = bm.load(store, version.version)
        if not rows.empty:
            benchmarks = dict(
                zip(rows["norm_key"].astype(str),
                    rows["benchmark"].astype(float))
            )
    spec = calculator.payload(benchmarks, version.version if version else "")
    return (
        f'<script type="application/json" id="calcdata">{json.dumps(spec)}</script>'
        '<div class="calculator" id="calcpanel"></div>'
    )


