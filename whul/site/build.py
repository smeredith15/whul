DEFAULT_OUT = Path("site")


def _slug(value: str) -> str:
    return "".join(c if c.isalnum() or c == "-" else "-" for c in value.lower())


#: What the banner says, keyed by what the simulation actually invented. A
#: banner that overstates is a banner nobody reads: once the rosters are real,
#: calling the players placeholders is false on every page.
BANNERS = {
    "everything": (
        "<strong>Simulated data.</strong> These rosters and players are invented "
        "placeholders so the app can be built before the draft is done. Nothing "
        "here is a real result."
    ),
    "scores_only": (
        "<strong>Placeholder scores.</strong> The rosters, players and prices are "
        "real. The scores are invented so the pages can be built before the season "
        "starts — no game has been played yet."
    ),
}


def _page(title: str, body: str, active: str, managers: list[str],
          depth: int = 0, stamp: str = "", simulated: str | bool = False) -> str:
    """One page's HTML. Depth sets how far up the shared assets are."""
    up = "../" * depth
    nav = [("index.html", "Standings"), ("about.html", "How scoring works")]
    current = ' aria-current="page"'
    links = "".join(
        f'<a href="{up}{href}"{current if label == active else ""}>{label}</a>'
        for href, label in nav
    )
    teams = "".join(
        f'<a href="{up}team/{_slug(m)}.html"'
        f'{current if m == active else ""}>{escape(manager_name(m))}</a>'
        for m in managers
    )
    text = BANNERS.get(simulated if isinstance(simulated, str) else "everything")
    banner = f'<div class="banner">{text}</div>' if simulated else ""
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{escape(title)}</title>
<link rel="stylesheet" href="{up}style.css">
</head>
<body>
<div class="wrap">
<header class="masthead">
  <h1><a href="{up}index.html" style="text-decoration:none">
    <span class="full">{escape(LEAGUE_NAME)}</span>
    <span class="short">{escape(LEAGUE_ABBR)}</span>
  </a></h1>
  <span class="stamp">{escape(stamp)}</span>
  <nav>{links}{teams}</nav>
</header>
{banner}
{body}
<footer>
  Generated by <code>python -m whul.cli site</code>. Scores are season-to-date,
  normalized so 100 is the 99th percentile of a draftable pool.
</footer>
</div>
<script src="{up}app.js"></script>
</body>
</html>
"""


def asset_profiles(
    store: Store, season: str, as_of, wanted: set[str], depth: int = 0
) -> dict[str, dict]:
    """Everything the profile window shows, for every asset the page mentions.

    Built once and embedded in the page. On a static site there is nothing to
    fetch from, so a profile has to already be there when it is clicked -- and
    for a few hundred assets that is a smaller payload than one photograph.
    """
    scores = store.query(
        "SELECT asset_id, league_points, scaled_score FROM daily_scores "
        "WHERE season = ? AND as_of = ?",
        (season, str(as_of)),
    ).set_index("asset_id")
    meta = store.query(
        "SELECT asset_id, display_name, league, role, asset_type FROM assets"
    ).set_index("asset_id")
    stats = store.read_stats(season, as_of)

    lines: dict[str, list[tuple[str, str]]] = {}
    finishes: dict[str, list[dict]] = {}
    notes: dict[str, list[str]] = {}
    if not stats.empty:
        for row in stats.to_dict("records"):
            asset_id = row["asset_id"]
            finishes[asset_id] = _finish_list(row)
            notes[asset_id] = _scaling_notes(row)
            lines[asset_id] = _stat_lines(row)

    out: dict[str, dict] = {}
    for asset_id in sorted(wanted):
        if not asset_id or asset_id not in meta.index:
            continue
        info = meta.loc[asset_id]
        name = str(info["display_name"])
        league = str(info["league"])
        badge = images.find("badge", _slug(league))
        out[asset_id] = {
            "name": escape(name),
            "meta": escape(f"{league} · {info['asset_type']}"),
            "avatar": images.avatar("asset", asset_id, name, size=52, depth=depth),
            "badge": (
                f'<img class="badge" src="{"../" * depth}{images.OUT_DIR}/badge/'
                f'{escape(badge.name)}" alt="{escape(league)}">' if badge else ""
            ),
            "raw": f"{float(scores.loc[asset_id, 'league_points']):,.1f}"
                   if asset_id in scores.index else "—",
            "scaled": f"{float(scores.loc[asset_id, 'scaled_score']):,.1f}"
                      if asset_id in scores.index else "—",
            "stats": lines.get(asset_id, []),
            "finishes": finishes.get(asset_id, []),
            "notes": notes.get(asset_id, []),
        }
    return out


