def _label_for(column: str) -> str:
    """A stat's name in words. `games_played` reads as debug output."""
    return STAT_LABELS.get(column, column.replace("_", " ").capitalize())


def _stat_lines(row: dict) -> list[tuple[str, str]]:
    """Every figure that went into the raw score, labelled."""
    out = []
    for column, value in row.items():
        if column in STAT_SKIP or value is None or value != value:
            continue
        # An empty string is a figure the scorer had nothing to put in, which
        # is not the same as a zero and reads as neither: "Continental entry"
        # followed by nothing at all.
        if isinstance(value, str) and not value.strip():
            continue
        if isinstance(value, (list, dict)):
            continue
        if isinstance(value, bool):
            text = "yes" if value else "no"
        elif isinstance(value, float):
            text = f"{value:,.1f}"
        else:
            text = str(value)
        out.append((_label_for(column), text))
    return out


def _finish_list(row: dict) -> list[dict]:
    """The athlete's actual finishes, newest first, where the sport has them."""
    value = row.get("finishes")
    if isinstance(value, str):
        try:
            value = json.loads(value)
        except (TypeError, ValueError):
            return []
    return value if isinstance(value, list) else []


def _bonus_moves(row: dict, was: dict) -> tuple[float, list[str]]:
    """What changed in the held bonus since the previous day, and by how much.

    A Champions League night moves nothing in the score -- the bonus is held
    until the competition finishes -- so without this the day it was played
    reads as a day nothing happened. The figures are inside ``bonus_detail``
    rather than in columns of their own, so they are differenced here by
    competition.
    """
    now = {d["competition"]: d for d in _bonus_list(row)}
    before = {d["competition"]: d for d in _bonus_list(was)}
    moved, lines = 0.0, []
    for name, entry in now.items():
        prior = before.get(name, {})
        games = float(entry.get("games") or 0) - float(prior.get("games") or 0)
        points = float(entry.get("points") or 0) - float(prior.get("points") or 0)
        adds = float(entry.get("adds") or 0) - float(prior.get("adds") or 0)
        if abs(games) < 0.05 and abs(points) < 0.05:
            continue
        moved += adds
        count = f"{games:g} game" + ("" if abs(games) == 1 else "s")
        lines.append(f"{name} {count} \u00b7 {points:,.1f}")
    return round(moved, 1), lines


def _bonus_list(row: dict) -> list[dict]:
    """Each competition paying a rate bonus, with the share that prices it.

    Kept out of the season totals deliberately. A row reading "Postseason bonus
    11.2" says nothing about what it was 11.2 *of*, and the shares are no longer
    one number: a Champions League run pays 5% of a season and the MLS Cup
    playoffs pay 10%, and a player can be in both.
    """
    value = row.get("bonus_detail")
    if isinstance(value, str):
        try:
            value = json.loads(value)
        except (TypeError, ValueError):
            return []
    if not isinstance(value, list):
        return []
    return [entry for entry in value
            if isinstance(entry, dict) and float(entry.get("games") or 0) > 0]


def _scaling_notes(row: dict) -> list[str]:
    """Why a figure here is not simply what the feed reported.

    A score that has been prorated or schedule-scaled looks like an ordinary
    one, and a manager checking the arithmetic against a box score would find
    it does not reconcile. Saying so is cheaper than being asked.
    """
    out = []
    factor = row.get("proration_factor")
    if isinstance(factor, (int, float)) and factor and factor == factor and factor != 1.0:
        out.append(
            f"Counting production is scaled by \u00d7{factor:.3f}, because this "
            f"league year covers a shorter window than the seasons the benchmark "
            f"was drawn from. One-off achievements are not scaled."
        )
    share = row.get("advanced_share")
    if isinstance(share, (int, float)) and share == share and 0 <= share < 1:
        out.append(
            f"Offense, Defense and WAR are shared out across this player's games "
            f"in the window ({share:.0%} of their season so far). The feed "
            f"reports them for the season to date only, and a season of run "
            f"values added to a few weeks of hits would overstate them several "
            f"times over."
        )

    factor = row.get("schedule_factor")
    if isinstance(factor, (int, float)) and factor and factor == factor and factor != 1.0:
        out.append(
            f"The benchmark for this league is lifted by \u00d7{factor:.3f} to "
            f"match a longer schedule than its history was played over."
        )
    return out


def _identity_lines(profile: dict | None, *tail: str) -> str:
    """The grey lines under a name: what they play, where, and against what.

    ``tail`` is whatever the caller wants on the end of the first line -- the
    league, usually, which a roster table already says in its own column and a
    results table does not.

    Empty parts are dropped rather than left as stray separators. Most of these
    are empty most of the season: a league that has not started has recorded no
    row, so there is no position and no club to show, and a page of names each
    followed by " · " would look broken rather than early.
    """
    if not profile:
        return ""
    # Deduplicated, because a club's own line now names its league and the
    # results table appends the league too: "Premier League · Champions League
    # · Premier League · Team" says one of those twice.
    parts: list[str] = []
    for part in (profile.get("position", ""), profile.get("team", ""), *tail):
        if part and part not in parts:
            parts.append(part)
    out = f'<span class="idl">{" · ".join(parts)}</span>' if parts else ""
    group = profile.get("group", "")
    return out + (f'<em class="grp">{group}</em>' if group else "")


def _asset_button(asset_id: str, name: str, counts: bool = True, depth: int = 0,
                  profile: dict | None = None) -> str:
    """A name that opens its profile, with what the name is underneath it.

    ``counts`` dims the row but does not strike the name. A benched slot's
    *score* is what is set aside; the player is not crossed out, their
    contribution is -- and a struck name reads like a player who has been
    dropped rather than one whose week was someone else's.

    The position and club go here rather than only in the window because a
    roster is sixty names and reading it should not need sixty clicks. The
    window still has all of it, which is what the click is for.
    """
    inner = escape(name)
    corner = profile.get("corner") if profile else None
    corner = tuple(corner) if corner else None
    logo = bool(profile.get("logo")) if profile else False
    return (
        f'<button class="assetlink" data-asset="{escape(asset_id or "")}" '
        f'type="button"><span class="who">'
        f"{images.avatar('asset', asset_id, name, size=26, depth=depth, badge=corner, logo=logo)}"
        f'<span class="stack"><span class="nm">{inner}</span>'
        f'{_identity_lines(profile)}</span></span></button>'
    )


def _counting_mix(
    mine: pd.DataFrame, profiles: dict[str, dict]
) -> list[tuple[str, list[tuple[str, float, str]]]]:
    """A manager's counting slots, grouped by category, biggest share first.

    Past six segments a part-to-whole figure stops being readable -- angles
    cannot be compared and adjacent hues blur -- so the tail folds into one
    "Other". A manager has nine contributing categories now and will have twice
    that once every league is in season, which the table beneath is for.
    """
    if mine.empty:
        return []
    counting = mine[mine["counts"].astype(bool) & (mine["score"] > 0)]
    if counting.empty:
        return []

    by_category: dict[str, list[tuple[str, float, str]]] = {}
    for row in counting.sort_values("score", ascending=False).itertuples():
        asset = str(row.asset_id or "")
        profile = profiles.get(asset)
        name = profile["name"] if profile else asset
        by_category.setdefault(str(row.category), []).append(
            (name, float(row.score), asset)
        )

    ranked = sorted(
        by_category.items(),
        key=lambda kv: sum(score for _, score, _ in kv[1]),
        reverse=True,
    )
    if len(ranked) <= charts.DONUT_SEGMENTS:
        return ranked
    head = ranked[:charts.DONUT_SEGMENTS - 1]
    tail = [h for _, holdings in ranked[charts.DONUT_SEGMENTS - 1:] for h in holdings]
    return head + [(charts.DONUT_OTHER, sorted(tail, key=lambda h: -h[1]))]


def _season_note(live: int, filled: int) -> str:
    """What the counting total is missing, said in the tile that shows it.

    A total of 1,900 in September and one of 4,000 in March are not a team
    improving; they are eleven leagues in season instead of five. The tile
    printed the date and left the reader to know that.
    """
    if not filled:
        return "nothing drafted yet"
    if live == filled:
        return "every slot in season"
    return f"{live} of {filled} slots in season"


def _in_season(
    mine: pd.DataFrame, profiles: dict[str, dict], day: date
) -> tuple[int, int]:
    """How many of a manager's counting slots are in a league that has started.

    Returns ``(in season, filled)``. The difference between the two is what a
    total is missing today, and it is the whole reason a counting total in
    September cannot be compared with one in February.

    Asked of the calendar rather than of the scores. A slot whose player is
    injured, benched, suspended or simply had a quiet week scores zero, and
    counting non-zero scores would file all of that under "not started" -- so a
    manager whose NFL back is hurt would look like a manager who has not
    drafted one. The league has started; the slot is in it; the zero is a
    result.

    The exception is a slot with no start date to ask about, which today is
    only the international squads: each plays in a different competition on a
    different calendar. There a score is the only evidence there is, so a zero
    is read as "the tournaments have not come round yet" -- the reading this
    function exists to avoid everywhere else, used here because nothing better
    exists.
    """
    from whul.config.league import in_season as league_in_season

    if mine.empty:
        return 0, 0
    filled = mine[mine["counts"].astype(bool) & mine["asset_id"].astype(bool)]
    if filled.empty:
        return 0, 0

    live = 0
    for row in filled.itertuples():
        profile = profiles.get(str(row.asset_id)) or {}
        started = league_in_season(str(profile.get("league") or ""), day)
        live += bool(float(row.score) > 0) if started is None else bool(started)
    return live, len(filled)


def _results_table(
    bars: pd.DataFrame, profiles: dict[str, dict], managers: list[str]
) -> str:
    """Every scored asset in one table, best first.

    The bar chart answers "how is my roster doing"; this answers "who is doing
    well", which is a different question and had no page. Sorted by normalized
    score because that is the only figure comparable across leagues -- a raw
    total is on a scale that differs per sport.

    Filtered in the browser rather than pre-split: twenty leagues is twenty
    tables nobody scrolls, and the interesting comparison is usually across two
    of them rather than within one.
    """
    if bars.empty:
        return '<p class="sub">Nothing scored yet.</p>'

    rows = []
    leagues: set[str] = set()
    kinds: set[str] = set()
    # `contributions` always carries it; a frame assembled by hand may not, and
    # a missing column should leave every row counting rather than none.
    has_counts = "counts" in bars.columns
    for row in bars.sort_values("score", ascending=False).itertuples():
        profile = profiles.get(row.asset_id)
        if not profile:
            continue
        league = profile.get("league", "")
        kind = profile.get("kind", "")
        leagues.add(league)
        kinds.add(kind)
        slot = theme.series_index(managers, row.manager_id) + 1
        rows.append(
            f'<tr data-league="{league}" data-kind="{kind}" '
            f'data-manager="{escape(str(row.manager_id))}" '
            f'data-counts="{1 if (not has_counts or row.counts) else 0}">'
            f'<td><button class="assetlink" data-asset="{escape(row.asset_id)}">'
            f'{profile["name"]}</button>'
            f'<span class="rowmeta">{_identity_lines(profile, league, kind)}</span>'
            f'</td>'
            f'<td><span class="who"><i class="swatch" '
            f'style="background: var(--series-{slot})"></i>'
            f'{escape(manager_name(row.manager_id))}</span></td>'
            f'<td class="num" data-score="{row.score:.4f}">{row.score:,.1f}</td></tr>'
        )
    if not rows:
        return '<p class="sub">Nothing scored yet.</p>'

    def chips(name: str, values: set[str]) -> str:
        # Already escaped: these come off the profiles, which hold HTML because
        # every other place they are used is HTML. Escaping again turned "Men's
        # Intl Soccer" into a chip reading "Men&#x27;s Intl Soccer" -- and the
        # filter went on working, because the row's own attribute was wrong in
        # exactly the same way.
        buttons = "".join(
            f'<button class="chip" data-filter="{name}" data-value="{v}" '
            f'aria-pressed="false">{v}</button>'
            for v in sorted(values) if v
        )
        return f'<div class="chips" role="group" aria-label="Filter by {name}">{buttons}</div>'

    # Everything is listed, including the assets on nothing yet -- two thirds
    # of the roster in September, when most leagues have not started. Listing
    # them is the honest default and burying them is the useful one, so the
    # toggle is here and off, rather than either being chosen for the reader.
    scoring_only = (
        '<div class="chips" role="group" aria-label="Hide unscored">'
        '<button class="chip" data-filter="scoring" data-value="yes" '
        'aria-pressed="false">Scoring only</button></div>'
    )
    # The same two figures the standings carry, over whatever the filter has
    # left showing. Unfiltered it *is* the standings, which is what makes it
    # readable: filter to one league and the same table answers "who is winning
    # that league", which is a question the season generates weekly and nothing
    # here could answer.
    totals = "".join(
        f'<tr data-manager="{escape(m)}">'
        f'<td><span class="who"><i class="swatch" '
        f'style="background: var(--series-{theme.series_index(managers, m) + 1})">'
        f'</i>{escape(manager_name(m))}</span></td>'
        f'<td class="num" data-total>0.0</td>'
        f'<td class="num benched" data-bench>0.0</td></tr>'
        for m in managers
    )
    return (
        '<table class="filtertotals" id="filtertotals">'
        '<thead><tr><th>Manager</th><th class="num">Counting</th>'
        '<th class="num">Bench</th></tr></thead>'
        f'<tbody>{totals}</tbody></table>'
        f'{chips("kind", kinds)}{chips("league", leagues)}{scoring_only}'
        '<p class="sub filtercount" data-count>Showing every scored asset.</p>'
        '<table class="results" id="resultstable">'
        '<thead><tr><th>Asset</th><th>Owner</th>'
        '<th class="num">Normalized</th></tr></thead>'
        f'<tbody>{"".join(rows)}</tbody></table>'
    )


#: What a league's feed is doing, worst first. The order is the order a reader
#: should look in: a league that has never been pulled is invisible by
#: construction, and one failing in season is the case this whole panel exists
#: for.
FEED_STATES = ("never pulled", "failing", "stale?", "waiting", "scoring")


def _feed_state(row: dict, in_season: bool | None) -> tuple[str, str]:
    """How a feed is doing, and what to say about it.

    The distinction that matters is between a league that is quiet because
    nothing has been played and one that is quiet because something broke.
    Both look identical in the standings -- a column of zeroes -- and they need
    opposite responses. `in_season` is what tells them apart, so it is asked
    rather than inferred from the message text, which changes.
    """
    if row.get("last_run_at") in (None, ""):
        return "never pulled", ("no run has ever fetched this league; it is not "
                                "in the nightly list")
    message = str(row.get("message") or "")
    if row.get("last_ok"):
        return "scoring", message
    if in_season is False:
        return "waiting", message or "the season has not opened yet"
    if in_season is None:
        # An international side has no start date: each plays a different
        # competition on a different calendar, so only a result can say the
        # season has begun. Reporting that as a failure would cry wolf all year.
        return "waiting", message or "no start date; only a result can say"
    return "failing", message or "the last run returned nothing, in season"


def _feed_rows(store: Store, season: str, as_of: str) -> list[dict]:
    """One row per source that feeds something this roster holds.

    Per source rather than per league, because that is the grain the record has
    -- `source_status` keeps one row per source, keyed on the source's own
    league, which for a source serving six competitions is the category rather
    than any of them. Listing it once per competition instead produced twelve
    rows reading "never pulled" about feeds that had run an hour earlier.

    A competition can legitimately appear twice: the Premier League is fed by
    `epl` for its clubs and `soccer-players` for its players, and either can
    fail without the other.
    """
    from whul.benchmark_sources import SOURCES
    from whul.config.league import competitions_for, in_season

    day = date.fromisoformat(str(as_of))
    held = set(store.query(
        "SELECT DISTINCT a.league FROM roster_slots r "
        "JOIN slot_occupancy o ON o.slot_id = r.slot_id AND o.end_date IS NULL "
        "JOIN assets a ON a.asset_id = o.asset_id WHERE r.season = ?", (season,),
    )["league"])
    status = {
        (row.source, row.league): row._asdict()
        for row in store.query("SELECT * FROM source_status").itertuples(index=False)
    }

    rows = []
    for key, source in SOURCES.items():
        covers = [lg for lg in (source.produces or competitions_for(source.league))
                  if lg in held]
        if not covers:
            continue
        row = status.get((key, source.league), {})
        # Whether the season has opened is asked of the competitions this
        # source actually serves. One of them being under way is enough for a
        # silent feed to be a fault rather than a quiet week.
        seasons = [in_season(lg, day) for lg in covers]
        started = True if any(v is True for v in seasons) else (
            False if all(v is False for v in seasons) else None
        )
        state, note = _feed_state(row, started)
        rows.append({
            "covers": covers, "source": key, "state": state, "note": note,
            "through": str(row.get("last_data_date") or ""),
            "rows": int(row.get("rows_last_run") or 0),
        })
    rank = {state: i for i, state in enumerate(FEED_STATES)}
    return sorted(rows, key=lambda r: (rank.get(r["state"], 0), r["covers"][0]))


def _feed_table(rows: list[dict], as_of: str) -> str:
    """The panel. Plain table: this is read, not compared."""
    if not rows:
        return "<p class='sub'>No feed has run yet.</p>"
    today = date.fromisoformat(str(as_of))
    body = []
    for row in rows:
        ago = ""
        if row["through"]:
            days = (today - date.fromisoformat(row["through"])).days
            ago = "today" if days <= 0 else f"{days}d ago"
        body.append(
            f"<tr class='feed-{_slug(row['state'])}'>"
            f"<td>{escape(', '.join(row['covers']))}</td>"
            f"<td class='src'>{escape(row['source'])}</td>"
            f"<td><span class='state'>{escape(row['state'])}</span></td>"
            f"<td>{escape(row['through'])}"
            f"{f' <span class=ago>{ago}</span>' if ago else ''}</td>"
            f"<td class='num'>{row['rows'] or '—'}</td>"
            f"<td class='why'>{escape(row['note'])}</td></tr>"
        )
    return (
        "<table class='feeds'><thead><tr><th>Covers</th><th>Source</th>"
        "<th>State</th><th>Data through</th><th class='num'>Rows</th>"
        "<th>What it said</th></tr></thead>"
        f"<tbody>{''.join(body)}</tbody></table>"
    )


